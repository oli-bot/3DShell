static char         g_settings_path[256];
static machine_ui_t *g_mui = NULL;

/* ── Persisting the project page's edits ──────────────────────────────
 * One place writes them, so the two callers (the per-frame retry and the
 * shutdown flush) cannot drift apart.
 *
 * The softkb overlay is not cosmetic: g_loaded_settings is only refreshed
 * at boot, while the soft keyboard keeps its own copy of every UI field
 * and syncs it back only on its own save.  Writing the struct without the
 * overlay therefore reverted theme / mascot / language / … to whatever
 * settings.ini held when DSSH started — the settings page's save re-reads
 * and re-overlays, but that only helps when it happens to be dirty in the
 * same frame.  softkb_export_settings() touches nothing but its own
 * fields, so the card list rides through untouched.
 *
 * Returns 1 when there is nothing left to write (or the write landed). */
static int project_settings_save(project_ui_t *pui, softkb_t *kb) {
    if (!project_ui_dirty(pui)) return 1;
    if (kb) softkb_export_settings(kb, &g_loaded_settings);
    if (settings_save(&g_loaded_settings, g_settings_path) != 0) return 0;
    project_ui_clear_dirty(pui);
    return 1;
}

static terminal_t *focus_term(void) { return g_win[g_focus].term; }

static int win_usable(const win_t *w) {
    return w->state == W_OPENING || w->state == W_LIVE;
}

static int win_count(void) {
    int n = 0;
    for (int i = 0; i < MAX_WINDOWS; i++)
        if (win_usable(&g_win[i])) n++;
    return n;
}

/* True when `slot` is the window the whole view rests on: retiring it would
 * leave no usable terminal, and focus_term() — which the renderer and every
 * banner write to — would go NULL. */
static int win_is_last(int slot) {
    return slot >= 0 && slot < MAX_WINDOWS &&
           win_usable(&g_win[slot]) && win_count() <= 1;
}

static void win_focus(int slot) {
    if (slot < 0 || slot >= MAX_WINDOWS) return;
    g_focus = slot;
    g_win[slot].dirty = 0;
    if (g_ime) ime_clear(g_ime);
}

/* Nearest window that can take focus when `slot` goes away.  Every caller
 * checks win_is_last() first, so another usable window always exists; the
 * `return 0` is only there to keep the function total. */
static int win_other(int slot) {
    for (int i = 1; i < MAX_WINDOWS; i++) {
        int cand = (slot + i) % MAX_WINDOWS;
        if (win_usable(&g_win[cand])) return cand;
    }
    return 0;
}

static void win_focus_rel(int dir) {
    if (win_count() <= 1) return;
    int i = g_focus;
    for (int step = 0; step < MAX_WINDOWS; step++) {
        i = (i + dir + MAX_WINDOWS) % MAX_WINDOWS;
        if (win_usable(&g_win[i])) break;
    }
    win_focus(i);
}

static void win_touch_all(void) {
    time_t now = time(NULL);
    for (int i = 0; i < MAX_WINDOWS; i++) {
        g_win[i].last_rx_at = now;
        g_win[i].last_tx_at = now;
    }
}

/* Bring one window's grid — the local widget and its remote PTY — in line
 * with the view geometry the user is looking at.  No-op when it already
 * matches, so calling it every frame is free.
 *
 * Only the focused window is ever asked to: a window-change is a SIGWINCH,
 * and a TUI answers one by repainting the whole screen.  Resizing hidden
 * windows therefore manufactures output on every one of them — that is the
 * ● that used to reappear on an idle window right after a START+L press.
 * A
 * background window keeps the geometry it had when it was last focused and
 * renegotiates the moment focus lands on it, one frame before it is drawn.
 * A window-change still pending from a refused EAGAIN is healed by
 * ssh_pty_tick in win_pump, not here. */
static void win_apply_view(ssh_client_t *ssh, int slot) {
    terminal_t *t = g_win[slot].term;
    if (!t || (t->cols == g_grid_cols && t->rows == g_grid_rows)) return;
    terminal_resize(t, g_grid_cols, g_grid_rows);
    ssh_set_pty_size_slot(ssh, slot, g_grid_cols, g_grid_rows);
}

/* Hand the closing window's note to the window the user lands on: the dying
 * one is about to stop being what they see. */
static void win_note(int slot, const char *why) {
    terminal_t *t = focus_term();
    if (!t) return;
    char line[224];
    snprintf(line, sizeof(line),
             "\x1b[90m[窗口 %d 已关闭 · X+Y▲ 新建]\x1b[0m\r\n", slot + 1);
    terminal_write(t, line);
    if (why && why[0]) {
        snprintf(line, sizeof(line), "\x1b[31m%s\x1b[0m\r\n", why);
        terminal_write(t, line);
    }
}

/* Open a new shell channel in a free slot. */
static void win_create(ssh_client_t *ssh) {
    if (!ssh || !ssh_is_connected(ssh)) return;   /* nothing to multiplex on */
    int slot = -1;
    for (int i = 0; i < MAX_WINDOWS; i++)
        if (g_win[i].state == W_EMPTY) { slot = i; break; }
    /* A window that only just closed is still draining its channel close, so
     * its slot may stay unavailable for a frame or two.  Hijacking it is not
     * an option: ssh_open_shell refuses a CLOSING channel. */
    if (slot < 0) {
        /* Without a line here the chord is indistinguishable from a broken
         * binding — the strip already reads 1·2·3·4, so say what is full. */
        terminal_t *t = focus_term();
        if (t) {
            char line[64];
            snprintf(line, sizeof(line),
                     "\x1b[90m[已达 %d 窗口上限]\x1b[0m\r\n", MAX_WINDOWS);
            terminal_write(t, line);
        }
        return;
    }

    /* A failed allocation leaves the slot exactly as it was: an empty one. */
    terminal_t *fresh = terminal_init(g_grid_cols, g_grid_rows);
    if (!fresh) return;
    g_win[slot].term = fresh;
    char line[96];
    snprintf(line, sizeof(line),
             "\x1b[90m窗口 %d 正在建立…\x1b[0m\r\n", slot + 1);
    terminal_write(g_win[slot].term, line);
    g_win[slot].state = W_OPENING;
    g_win[slot].dirty = 0;
    g_win[slot].last_rx_at = g_win[slot].last_tx_at = time(NULL);
    win_focus(slot);
    /* A fresh shell lands in the login directory, so a card picked for it
     * starts from a clean slate rather than inheriting whatever the window
     * that was in this slot before had been cd-ed into. */
    g_win_cwd[slot][0]     = 0;
    g_pending_cmd[slot][0] = 0;
    g_win_just_created     = slot;
}

/* Retire a window: start its channel's close, move focus somewhere usable, and
 * tell the user.  The grid itself goes on the next pump, once libssh2 has
 * actually freed the channel (see win_pump). */
static void win_close(ssh_client_t *ssh, int slot, const char *why) {
    if (slot < 0 || slot >= MAX_WINDOWS) return;
    win_t *w = &g_win[slot];
    if (w->state == W_EMPTY || w->state == W_CLOSED) return;
    /* The card page raise is keyed off this index, and it can be deferred
     * by up to an AI-modal fade (modal_open outlives modal_capture) — long
     * enough for the pump below to fail this channel open and retire the
     * slot.  Clearing it here is what keeps the page from later opening
     * for a window that no longer exists, where picking a card would park
     * the command in g_pending_cmd and silently do nothing.  win_prune()
     * does the same for the whole-session case. */
    if (g_win_just_created == slot) g_win_just_created = -1;
    (void)ssh_close_slot(ssh, slot);
    w->state = W_CLOSED;
    w->dirty = 0;
    if (g_focus == slot) win_focus(win_other(slot));
    win_note(slot, why);
}

/* The X+Y▼ chord.  The last window is the session's own shell — closing it
 * would leave nothing on screen, and `exit` is what ends a session. */
static void win_close_focused(ssh_client_t *ssh) {
    if (!ssh || !ssh_is_connected(ssh)) return;
    if (win_count() <= 1) {
        terminal_t *t = focus_term();
        if (t)
            terminal_write(t, "\x1b[90m[只剩一个窗口，X+Y▲ 可新建]\x1b[0m\r\n");
        return;
    }
    win_close(ssh, g_focus, NULL);
}

/* The session is gone, so every channel went with it.  Keep the terminal the
 * user was looking at as window 0 — window 0 itself may have been closed
 * earlier — because that is the one the reconnect banners write to and the
 * one the renderer must never find NULL. */
static void win_prune(void) {
    terminal_t *keep = focus_term();
    int keep_slot = g_focus;
    for (int i = 0; i < MAX_WINDOWS; i++) {
        if (g_win[i].term && i != keep_slot) terminal_free(g_win[i].term);
        g_win[i].term = NULL;
        g_win[i].state = W_EMPTY;
        g_win[i].dirty = 0;
        g_win[i].last_rx_at = g_win[i].last_tx_at = 0;
        /* The session is gone, so every channel went with it — a remembered
         * cd target or a line still queued for an opening shell would be
         * aimed at a slot the next connection reuses for something else. */
        g_win_cwd[i][0]     = 0;
        g_pending_cmd[i][0] = 0;
    }
    /* A window the chord created a moment ago has no shell left to raise
     * the card page for, and the slot index would be stale after the
     * reconnect reuses it. */
    g_win_just_created = -1;
    g_win[0].term = keep;
    g_win[0].state = keep ? W_LIVE : W_EMPTY;
    win_focus(0);
}

/* Advance one window's channel machine and drain its bytes.  `chunks` bounds
 * how many READ_BUFSZ reads one frame may spend on it.  Returns -2 when the
 * session died, 0 otherwise. */
static int win_pump(ssh_client_t *ssh, int slot, char *rbuf, int chunks,
                    softkb_t *kb, int is_focus) {
    win_t *w = &g_win[slot];

    if (w->state == W_EMPTY) return 0;

    if (w->state == W_CLOSED || !w->term) {
        /* A refused open leaves the half-built channel draining; nobody else
         * owns this slot any more, so finish it here.  Once libssh2 has freed
         * the channel the terminal goes with it and the slot is reusable —
         * ssh_open_shell refuses a CLOSING slot. */
        if (ssh_close_slot(ssh, slot) != 1) {
            if (w->term) {
                terminal_free(w->term);
                w->term = NULL;
            }
            w->state = W_EMPTY;
            w->dirty = 0;
        }
        return 0;
    }
    if (w->state == W_OPENING) {
        char err[128] = {0};
        int rc = ssh_open_shell(ssh, slot, g_grid_cols, g_grid_rows,
                                err, sizeof(err));
        if (rc == 0) {
            w->state = W_LIVE;
            w->last_rx_at = time(NULL);
        } else if (rc > 0) {
            return 0;                      /* still in flight — next frame */
        } else if (win_is_last(slot)) {
            /* No shell channel left alive at all: ssh_disconnect + the
             * SELECT-reconnect banner is the honest outcome, and it keeps this
             * terminal on screen instead of leaving the frame empty. */
            return -2;
        } else {
            win_close(ssh, slot, err[0] ? err : NULL);
        }
        return 0;
    }

    /* Heal a window-change that came back EAGAIN on the frame it was asked. */
    (void)ssh_pty_tick(ssh, slot);

    for (int i = 0; i < chunks; i++) {
        int n = ssh_read_slot(ssh, slot, rbuf, READ_BUFSZ);
        if (n > 0) {
            /* The debug page's 32-byte ring would be an unreadable mix of
             * four shells if every channel fed it. */
            if (is_focus) softkb_record_recv(kb, rbuf, n);
            terminal_write_bytes(w->term, rbuf, n);
            flush_terminal_responses_slot(ssh, slot, w->term);
            w->last_rx_at = time(NULL);
            if (!is_focus) w->dirty = 1;
            continue;
        }
        if (n == -2) return -2;
        if (n == -1) {
            /* The remote shell exited — `exit` is how a window closes.  For
             * the last window there is nothing to fall back to, so that is
             * the end of the session rather than an empty frame. */
            if (win_is_last(slot)) return -2;
            win_close(ssh, slot, NULL);
        }
        return 0;
    }
    return 0;
}

static u8  g_battery_pct = 100;
static u8  g_is_charging = 0;
static int g_battery_timer = 50;

static void poll_battery(void) {
    if (++g_battery_timer >= 60) {
        g_battery_timer = 0;
        u8 pct = 0;
        if (R_SUCCEEDED(mcuHwcInit())) {
            MCUHWC_GetBatteryLevel(&pct);
            mcuHwcExit();
            g_battery_pct = pct;
        }
        u8 chg = 0;
        if (R_SUCCEEDED(ptmuInit())) {
            PTMU_GetBatteryChargeState(&chg);
            ptmuExit();
            g_is_charging = chg;
        }
    }
}

/* ── Window strip (bottom bar / dual-screen overlay) ─────────────────
 * `1·2●·3` — one number per window, the focused one in the palette's primary
 * text role, a ● after a background tab that got output nobody has seen yet
 * (cleared the moment the user tabs to it).  Nothing is drawn while only one
 * window exists, so the single-tab bottom row stays byte-for-byte what it
 * always was.  Closing a window drops its number; the strip is a list of the
 * tabs you can actually switch to.
 *
 * Layout is token-by-token because each piece wants a different colour, and
 * every glyph here is narrow (6 px), so widths stay cheap to sum. */
#define WIN_STRIP_MAX_TOK (MAX_WINDOWS * 3)

typedef struct {
    char     text[8];
    uint32_t color;     /* RGBA 0xRRGGBBAA, as renderer_draw_text_px wants it */
} win_tok_t;

static int win_strip_tokens(const softkb_t *kb, win_tok_t *tok, int maxtok) {
    int last = -1;
    for (int i = 0; i < MAX_WINDOWS; i++)
        if (win_usable(&g_win[i])) last = i;
    if (last < 1) return 0;                   /* zero or one window */

    const uint32_t dim = softkb_info_dim(kb);
    int n = 0;
    for (int i = 0; i <= last; i++) {
        if (!win_usable(&g_win[i])) continue;
        if (n + 3 > maxtok) break;            /* never split a number+dot pair */
        if (n) {
            snprintf(tok[n].text, sizeof(tok[n].text), "·");
            tok[n].color = dim;
            n++;
        }
        snprintf(tok[n].text, sizeof(tok[n].text), "%d", i + 1);
        tok[n].color = (i == g_focus) ? softkb_tab_active_color(kb) : dim;
        n++;
        if (g_win[i].dirty && i != g_focus) {
            snprintf(tok[n].text, sizeof(tok[n].text), "●");
            tok[n].color = softkb_unread_color(kb);
            n++;
        }
    }
    return n;
}

/* Pixel width the strip would consume, 0 when there is nothing to show. */
static int win_strip_width(const softkb_t *kb) {
    win_tok_t tok[WIN_STRIP_MAX_TOK];
    int n = win_strip_tokens(kb, tok, WIN_STRIP_MAX_TOK);
    int w = 0;
    for (int i = 0; i < n; i++) w += renderer_utf8_text_width_px(tok[i].text);
    return w;
}

/* Draw left-aligned at `x`, returning the pixel just past the last token. */
static int win_strip_draw(const softkb_t *kb, int x, int y) {
    win_tok_t tok[WIN_STRIP_MAX_TOK];
    int n = win_strip_tokens(kb, tok, WIN_STRIP_MAX_TOK);
    for (int i = 0; i < n; i++) {
        renderer_draw_text_px(x, y, tok[i].text, tok[i].color);
        x += renderer_utf8_text_width_px(tok[i].text);
    }
    return x;
}

/* Dual-screen one-terminal mode has no bottom bar — the whole lower screen is terminal
 * space — so the strip floats over it as a status chip, right-aligned.  It
 * needs the plate: bare text over live terminal glyphs is unreadable, which is
 * why the voice badge on the left has one too. */
static void draw_window_strip_dual(renderer_t *r, const softkb_t *kb) {
    win_tok_t tok[WIN_STRIP_MAX_TOK];
    int n = win_strip_tokens(kb, tok, WIN_STRIP_MAX_TOK);
    if (n <= 0) return;
    int w = 0;
    for (int i = 0; i < n; i++) w += renderer_utf8_text_width_px(tok[i].text);
    /* Every glyph here is narrow, so the chip is exactly cell-aligned. */
    int cells = w / FONT_CELL_W;
    renderer_draw_rect_cells(r, R_BOT_COLS - cells - 1, 16, cells + 1, 1,
                             softkb_chip_bg(kb));
    win_strip_draw(kb, (R_BOT_COLS - cells) * FONT_CELL_W, 16 * FONT_CELL_H);
}

/* Right edge of the mascot's walkable strip, in bottom-panel pixels.
 * Deliberately NOT R_BOT_PX_W: the strip stops short of the panel edge so
 * the sprite never sits flush against the bezel, and the mascot's own
 * width is subtracted again inside mascot_set_bounds()/clamp_and_bounce(),
 * so this is the x the sprite's *right edge* may reach.  The init call in
 * main() and the per-frame re-measure in draw_bottom_bar() must agree on
 * it; they used to each spell 302. */
#define MASCOT_ROW_X_MAX 302

/* Bottom row (y=214..239): info strip on the left, mascot on the right.
 * The strip's width varies with what it shows (date+time+battery vs.
 * date+time vs. hidden), so the mascot's walkable region is re-measured
 * per frame to start right after the text — the two never overlap.
 * Every colour here is a role in the active theme palette: the clock and
 * the resting battery text use hint_fg, the battery digits switch to
 * batt_chg (while charging — green) and batt_crit (<10%). */
static void draw_bottom_bar(const softkb_t *kb, mascot_t *mc) {
    if (softkb_in_debug(kb) || softkb_settings_open(kb)) return;

    int info_mode = softkb_bottom_info_mode(kb);
    char time_buf[16] = "";
    char batt_buf[8]  = "";
    if (info_mode == 0 || info_mode == 1) {
        time_t now = time(NULL);
        struct tm lt;
        localtime_r(&now, &lt);
        snprintf(time_buf, sizeof(time_buf), "%02d-%02d %02d:%02d",
                 lt.tm_mon + 1, lt.tm_mday, lt.tm_hour, lt.tm_min);
        if (info_mode == 0)
            snprintf(batt_buf, sizeof(batt_buf), "%s%d%%",
                     g_is_charging ? "+" : "", g_battery_pct);
    }

    int strip_w = win_strip_width(kb);
    int time_w = renderer_utf8_text_width_px(time_buf);
    int batt_w = renderer_utf8_text_width_px(batt_buf);
    int strip_gap = (strip_w && time_w) ? FONT_CELL_W : 0;
    int total_w = strip_w + strip_gap + time_w + batt_w +
                  ((time_w && batt_w) ? FONT_CELL_W : 0);
    mascot_set_bounds(mc, (total_w > 0) ? 2 + total_w + 6 : 2,
                      MASCOT_ROW_X_MAX);

    uint32_t dim = softkb_info_dim(kb);
    /* Unlike the clock and battery, the strip ignores bottom_info_mode: once
     * there is more than one shell, which one you are looking at is not
     * optional information. */
    int x = 2;
    if (strip_w > 0) {
        win_strip_draw(kb, x, 221);
        x += strip_w + strip_gap;
    }
    if (time_w > 0) {
        renderer_draw_text_px(x, 221, time_buf, dim);
        x += time_w + ((time_w && batt_w) ? FONT_CELL_W : 0);
    }
    if (batt_w > 0) {
        uint32_t batt_color = dim;
        if (g_battery_pct < 10)      batt_color = softkb_batt_crit_color(kb);
        else if (g_is_charging)      batt_color = softkb_batt_chg_color(kb);
        else if (g_battery_pct < 20) batt_color = softkb_batt_warn_color(kb);
        /* x already carries the one-FONT_CELL_W gap that matches the space in
         * the old combined string; y=221 centers 12-px text in the row. */
        renderer_draw_text_px(x, 221, batt_buf, batt_color);
    }
    if (softkb_mascot_enabled(kb)) {
        mascot_set_species(mc, softkb_mascot_species(kb));
        mascot_draw(mc);
    }
}

/* Recording countdown — a 3 px bar pinned to the very bottom edge of the
 * info row, floating above the clock, battery and roaming mascot.  It only
 * exists while a take is running: full width when the press starts
 * recording, shrinking left-anchored against the user's 15/30/60 s ceiling,
 * green → yellow over the last fifth → red over the last tenth.  Released
 * L or an auto-stop cap both leave the state, and with it the bar.
 *
 * Called once after the bottom-screen render chain rather than from inside
 * draw_bottom_bar, which opts out for the debug overlay and the settings
 * page while a take may still be running. */
#define REC_BAR_X    2
#define REC_BAR_W    (R_BOT_PX_W - 2 * REC_BAR_X)   /* 316 */
#define REC_BAR_Y    236
#define REC_BAR_H    3
/* Fixed traffic-light hues, not theme roles: voice_status_bg() hardcodes the
 * recording tint across all four themes for the same reason — what a
 * countdown colour *means* outranks what a palette happens to look like. */
#define REC_BAR_OK   0x9ece6affu   /* green  */
#define REC_BAR_WARN 0xe0af68ffu   /* yellow */
#define REC_BAR_END  0xf7768effu   /* red    */

static void draw_record_countdown_bar(const voice_t *voice) {
    if (voice_state(voice) != VOICE_RECORDING) return;

    int total_ms = voice_get_max_record_sec(voice) * 1000;
    if (total_ms <= 0) return;
    int rem_ms = voice_record_remaining_ms(voice);
    if (rem_ms < 0) rem_ms = 0;
    if (rem_ms > total_ms) rem_ms = total_ms;

    /* Integer-only ramp: add half the divisor to round instead of using a
     * float divide.  The product peaks at 316 × 60000, nowhere near
     * INT_MAX. */
    int w = (REC_BAR_W * rem_ms + total_ms / 2) / total_ms;
    if (w < 1) w = 1;              /* never blink out before the cap bites */
    if (w > REC_BAR_W) w = REC_BAR_W;

    uint32_t col = (rem_ms <= total_ms / 10)     ? REC_BAR_END
                 : (rem_ms <= total_ms / 5)      ? REC_BAR_WARN
                                                 : REC_BAR_OK;
    /* z 0.62: above the terminal glyphs (0.3), strip text (0.5) and the
     * mascot body (0.6); the crab's mic prop sits at y≈214..220, clear of
     * this row, so nothing needs to beat its 0.7. */
    renderer_draw_rect_px(REC_BAR_X, REC_BAR_Y, w, REC_BAR_H, 0.62f, col);
}

static void clear_secret(char *s, size_t len) {
    volatile unsigned char *p = (volatile unsigned char *)s;
    while (len-- > 0) *p++ = 0;
}

/* The pre-connect frame: nothing is known about the session yet, so this
 * is the plain single-screen view with no bottom bar — deliberately not
 * render_frame, which assumes a live terminal, a mascot and a grid mode. */
static void render_connecting_frame(C3D_RenderTarget *top,
                                    C3D_RenderTarget *bot,
                                    renderer_t *renderer, terminal_t *term,
                                    softkb_t *keyboard,
                                    keyboard_t *physical_keyboard) {
    C3D_FrameBegin(C3D_FRAME_SYNCDRAW);
    C2D_TargetClear(top, terminal_get_c2d_bg(term));
    C2D_SceneBegin(top);
    renderer_draw_terminal(renderer, term);
    C2D_TargetClear(bot, softkb_bottom_c2d_bg(keyboard));
    C2D_SceneBegin(bot);
    softkb_draw(keyboard, renderer, physical_keyboard);
    C3D_FrameEnd(0);
}

/* The dual-screen bottom half: the rows after the top screen's, shown at one of
 * three widths.  AUTO follows use_alt (a full-screen TUI gets the
 * center-crop at full cell width, a shell gets the squeeze), SQUEEZE always
 * compresses every column into the panel, TRIM drops a few edge columns so
 * the rest compress less, and CENTER always crops to the middle.
 * bot_mode is the debug-page override (softkb_dual_bottom_mode). */
static void draw_dual_bottom(renderer_t *r, terminal_t *term, int bot_mode) {
    int half = r->top_rows;            /* rows on one physical panel */
    int cols = r->top_cols;            /* the grid width being displayed */
    if (bot_mode == 2 || (bot_mode == 0 && term->use_alt)) {
        renderer_draw_terminal_window_centered(r, term, half, half,
                                               r->bot_cols);
    } else if (bot_mode == 3) {
        int keep = cols - DUAL_TRIM_LOST;
        renderer_draw_terminal_window_crop_scaledx(
            r, term, half, half, DUAL_TRIM_OFF_L, keep,
            (float)r->bot_px / ((float)keep * (float)r->cell_w));
    } else {
        renderer_draw_terminal_window_scaledx(
            r, term, half, half, cols,
            (float)r->bot_px / ((float)cols * (float)r->cell_w));
    }
}

/* Draw one frame on both panels.  The main loop and the single frame
 * flushed before a blocking reconnect handshake share this: the row split,
 * the bottom-half width choice and every overlay live here alone, so the
 * reconnect frame cannot fall behind the running one.
 *
 * aim may be NULL — the reconnect frame has no modal layer, since SELECT
 * only reaches it while no modal is open. */
static void render_frame(renderer_t *r, C3D_RenderTarget *top,
                         C3D_RenderTarget *bot, terminal_t *term,
                         softkb_t *kb, keyboard_t *kbd, mascot_t *mc,
                         voice_t *voice, ai_modal_t *aim, int dual_term,
                         project_ui_t *pui) {
    /* The project page owns both screens while it is up.  It borrows the
     * soft keyboard for text entry rather than growing one of its own, so
     * the bottom screen has two possible owners and this is the only place
     * that decides which.  The machine picker rents the same surface for
     * its rename field, which is why it appears in both halves of this
     * function. */
    int pui_up   = project_ui_visible(pui);
    int pui_keys = pui_up && project_ui_wants_keyboard(pui);
    int mui_up   = g_mui && machine_ui_visible(g_mui);
    int mui_keys = mui_up && machine_ui_wants_keyboard(g_mui);
    /* Which layer owns the TOP panel decides its clear colour, exactly as
     * on the bottom below: the terminal paints its own background out of
     * terminal_get_bg(), so a page that has borrowed the top panel must be
     * cleared to the keyboard palette instead — otherwise the page sits on
     * the terminal's colour and, in a theme.ini, on a different colour from
     * its own bottom half. */
    int page_top = mui_up || pui_up;

    C3D_FrameBegin(C3D_FRAME_SYNCDRAW);
    C2D_TargetClear(top, page_top ? softkb_bottom_c2d_bg(kb)
                                  : terminal_get_c2d_bg(term));
    C2D_SceneBegin(top);
    if (mui_up) {
        /* The machine picker owns the top screen too. */
        machine_ui_draw_top(g_mui, &g_cfg, r, softkb_palette(kb));
    } else if (pui_up) {
        project_ui_draw_top(pui, &g_loaded_settings, r, softkb_palette(kb));
    } else if (softkb_settings_open(kb)) {
        /* Dual-screen settings page: the item list replaces the terminal up
         * here; the selected item's detail card is on the bottom screen. */
        softkb_draw_settings(kb, r);
    } else if (dual_term) {
        renderer_draw_terminal_window(r, term, 0, r->top_rows, r->top_cols);
    } else {
        renderer_draw_terminal(r, term);
    }

    /* Which layer owns the bottom panel decides what it must be cleared
     * to: draw_window() skips every cell whose background equals
     * terminal_get_bg(term) on the assumption that the clear already
     * painted it, so a terminal painted over a keyboard-coloured clear
     * shows the keyboard colour in every default cell — a seam against
     * the top half, which was cleared with terminal_get_c2d_bg(term).
     * Both values are already fixed by the time we clear. */
    int dual_bottom = dual_term && !softkb_settings_open(kb) && !pui_up && !mui_up;
    C2D_TargetClear(bot, dual_bottom ? terminal_get_c2d_bg(term)
                                     : softkb_bottom_c2d_bg(kb));
    C2D_SceneBegin(bot);
    if (mui_up && !mui_keys) {
        machine_ui_draw_bot(g_mui, &g_cfg, r, softkb_palette(kb));
    } else if (pui_up && !pui_keys) {
        project_ui_draw_bot(pui, &g_loaded_settings, r, softkb_palette(kb));
    } else if (dual_bottom) {
        draw_dual_bottom(r, term, softkb_dual_bottom_mode(kb));
        /* The voice badge and the window strip float over the terminal —
         * one-terminal mode is the only view with no bottom bar to hang
         * the strip on. */
        softkb_draw_voice_badge(kb);
        draw_window_strip_dual(r, kb);
    } else {
        softkb_draw(kb, r, kbd);
        /* Bottom row: info on the left, mascot on the right (no-op while
         * the debug overlay is up — that page draws its own background). */
        draw_bottom_bar(kb, mc);
    }

    /* The recording countdown floats over whichever bottom view is up, so
     * one call after the branch covers keyboard mode, one-terminal mode,
     * the debug page and the settings page alike. */
    draw_record_countdown_bar(voice);

    /* M12 — the modal lays over softkb + clock + mascot, drawn last so its
     * dimming overlay correctly covers everything below. */
    if (aim) ai_modal_draw(aim, softkb_palette(kb));

    C3D_FrameEnd(0);
}

/* Run the macOS keychain bootstrap on a freshly connected session, if a
 * keychain password is configured (no-op otherwise).  Shared between the
 * initial connect and the SELECT-key reconnect, so a reconnected macOS
 * session gets its keychain unlocked again.  Returns the session pointer,
 * or NULL if a hard disconnect during bootstrap tore the session down. */
static ssh_client_t *keychain_bootstrap(ssh_client_t *ssh,
                                        const ssh_machine_t *m,
                                        terminal_t *term, renderer_t *r,
                                        softkb_t *kb, keyboard_t *kbd,
                                        C3D_RenderTarget *top,
                                        C3D_RenderTarget *bot,
                                        char *err, int err_sz) {
    if (!ssh || !m->macos_keychain_password[0]) return ssh;

    /* Keep this local-only progress line visible while bootstrap blocks,
     * then reset again so fish CPR uses remote coordinates. */
    terminal_write(term, "\x1b[36mUnlocking macOS keychain...\x1b[0m\r\n");
    render_connecting_frame(top, bot, r, term, kb, kbd);
    terminal_reset(term);

    keychain_report_t report = { -1, -1 };
    int unlock_rc = unlock_macos_keychain(
        ssh, term, m->macos_keychain_password, &report, err, err_sz);

    /* ssh_read()/ssh_write() clear the connected flag on a hard error.
     * Do not leave a non-NULL but unusable session in the idle loop. */
    if (!ssh_is_connected(ssh)) {
        if (unlock_rc == 0)
            snprintf(err, (size_t)err_sz,
                     "SSH disconnected during keychain bootstrap");
        char line[320];
        snprintf(line, sizeof(line), "\x1b[31mSSH error:\x1b[0m %s\r\n", err);
        terminal_write(term, line);
        ssh_disconnect(ssh);
        return NULL;
    }
    if (unlock_rc != 0) {
        /* Completed commands print FAILED + exit codes themselves.
         * Only transport/prompt timeouts need a local fallback. */
        if (report.unlock_status < 0 && report.verify_status < 0) {
            /* A prompt/result timeout can leave `security` owning the
             * foreground PTY. Abort it before handing control to the
             * user so keyboard input reaches the normal shell. */
            (void)startup_write_all(ssh, "\x03\n", 2, 2000);
            char line[320];
            snprintf(line, sizeof(line),
                     "\x1b[33mkeychain bootstrap failed:\x1b[0m %s\r\n", err);
            terminal_write(term, line);
        }
    }
    return ssh;
}

/* Snap the local terminal view to the bottom (canceling any user-side
 * scrollback peek) right before sending a key.  This way the user always
 * sees what they just typed, even if they were glancing at history. */
static void send_to_ssh(ssh_client_t *ssh, int slot,
                        const char *bytes, int n, mascot_t *mc) {
    if (!ssh || !ssh_is_connected(ssh) || n <= 0) return;
    if (slot < 0 || slot >= MAX_WINDOWS) return;
    /* No channel, no send: typing on a window whose shell exited must not
     * leak the keystrokes into whichever window happens to be live. */
    if (ssh_slot_state(ssh, slot) != SSH_SLOT_LIVE) return;
    terminal_t *term = g_win[slot].term;
    if (term && term->sb_offset != 0) terminal_scroll_view(term, -term->sb_offset);
    if (ssh_write_slot(ssh, slot, bytes, n) < 0) return;
    g_win[slot].last_tx_at = time(NULL);
    /* Kick the typing animation once per send so the crab pecks its
     * claws on every keystroke / handwriting commit / voice glyph. */
    if (mc) mascot_type_kick(mc);
}

/* Establish (or re-establish) the SSH session using the loaded config.
 * Used both for the initial connect at startup and for the SELECT-key
 * reconnect after a hard disconnect (lid-close sleep kills the TCP).
 * On success: returns a new ssh_client_t, resets the local terminal
 * (fish CPR needs remote coordinates) and sizes the PTY.  On failure:
 * returns NULL, writes the red SSH-error banner + the diagnostic in
 * err. */
static ssh_client_t *reconnect_ssh(const ssh_machine_t *m,
                                   ts3ds *tailscale,
                                   terminal_t *term,
                                   char *err, int err_sz) {
    ssh_client_t *ssh = ssh_connect_pubkey(
        m->host, m->port, m->user,
        m->key_path, NULL,
        m->passphrase[0] ? m->passphrase : NULL,
        g_grid_cols, g_grid_rows,
        tailscale,
        err, err_sz);

    if (!ssh) {
        char line[256];
        snprintf(line, sizeof(line), "\x1b[31mSSH error:\x1b[0m %s\r\n", err);
        terminal_write(term, line);
        return NULL;
    }

    /* Local banners ("Reconnecting...", startup text) are not part of the
     * remote PTY screen. Reset before parsing shell output so fish's
     * cursor-position queries see the same coordinate system as sshd. */
    terminal_reset(term);
    /* Window 0 is the channel this session came up with. */
    ssh_set_pty_size_slot(ssh, 0, g_grid_cols, g_grid_rows);
    return ssh;
}

/* Bring Tailscale up, and only once the user has actually chosen a machine —
 * connect_and_open() calls this, main()'s boot prologue deliberately does
 * not.  The session is created at most once; a failed attempt is retried on
 * the next user-initiated connect, because that is what a retry is for.
 *
 * Returns the session to use as a transport, or NULL to connect directly.
 * NULL is not a fatal error: DSSH_TAILSCALE_PATH defaults to "auto", i.e.
 * Tailscale is an alternative route to the same servers, so a bring-up
 * that fails or is not configured falls through to the plain socket.  It
 * used to `goto idle_loop` here, which skipped the machine picker AND the
 * SSH connect and left the user in a terminal that could never come up —
 * with the only way out being SELECT, which nothing on screen mentioned. */
static ts3ds *tailscale_bring_up(terminal_t *term, renderer_t *r,
                                 C3D_RenderTarget *top, C3D_RenderTarget *bot,
                                 softkb_t *kb, keyboard_t *kbd) {
    if (g_tailscale) return g_tailscale;
    /* Intent, sampled once per process and then remembered.  Re-asking
     * config_tailscale_should_start() on every connect gets the wrong
     * answer in a way nobody sees: this function wipes
     * g_cfg.tailscale_auth_key once the attempt is over (it has served its
     * purpose and must not sit in RAM), and on a card that arrived with an
     * auth key but no `tailscale_autostart` yet, that makes should_start()
     * answer 0 from then on.  So a single failed dial — a control plane
     * briefly unreachable, Wi-Fi flapped — and every later connect in the
     * same session stopped trying Tailscale at all, silently, with nothing
     * on screen and no way back except a reboot.  A card that asked for
     * Tailscale keeps asking for the rest of the session, and a
     * user-initiated reconnect really does re-dial. */
    if (g_ts_intent < 0)
        g_ts_intent = config_tailscale_should_start(&g_cfg) ? 1 : 0;
    if (!g_ts_intent) return NULL;

    ts3ds_config tc;
    ts3ds_config_init(&tc);
    tc.auth_key   = g_cfg.tailscale_auth_key[0] ? g_cfg.tailscale_auth_key
                                               : NULL;
    tc.hostname   = g_cfg.tailscale_hostname;
    tc.state_path = g_cfg.tailscale_state;
    tc.control_url = g_cfg.tailscale_control_url;
    tc.connect_timeout_ms = DSSH_TAILSCALE_CONNECT_MS;
    if (ts3ds_path_policy_parse(DSSH_TAILSCALE_PATH, &tc.path_policy) !=
        TS3DS_OK) {
        char line[192];
        snprintf(line, sizeof(line),
                 "\x1b[33mTailscale disabled:\x1b[0m invalid path "
                 "policy='%.64s' (use auto, direct, peer-relay, or "
                 "derp) — connecting directly\r\n", DSSH_TAILSCALE_PATH);
        terminal_write(term, line);
        return NULL;
    }
    if (DSSH_TAILSCALE_VERBOSE) {
        tc.log = tailscale_debug_capture;
        tc.log_userdata = &g_tailscale_debug;
    }

    terminal_write(term,
                   "\x1b[36mConnecting to Tailscale...\x1b[0m\r\n");
    if (DSSH_TAILSCALE_VERBOSE) {
        char line[256];
        snprintf(line, sizeof(line),
                 "  node=%.63s auth=%s path=%.16s state=%.96s\r\n",
                 g_cfg.tailscale_hostname,
                 g_cfg.tailscale_auth_key[0] ? "yes" : "no",
                 ts3ds_path_policy_name(tc.path_policy),
                 g_cfg.tailscale_state);
        terminal_write(term, line);
    }
    /* One frame before the blocking dial, so the line above is on screen
     * for however long it takes.  Nothing else can run until it returns —
     * libts3ds dials on this thread — which is exactly why the caller puts
     * this after the machine picker rather than before it. */
    render_connecting_frame(top, bot, r, term, kb, kbd);

    ts3ds *ts = ts3ds_new(&tc);
    int rc = ts ? ts3ds_up(ts) : TS3DS_ERR_ARGUMENT;
    memset(g_cfg.tailscale_auth_key, 0, sizeof(g_cfg.tailscale_auth_key));
    tailscale_debug_flush(&g_tailscale_debug, term);

    if (!ts || rc != TS3DS_OK) {
        const char *reason = ts ? ts3ds_last_error(ts)
                                : "invalid Tailscale configuration";
        char line[256];
        snprintf(line, sizeof(line),
                 "\x1b[33mTailscale unavailable (rc=%d status=%d):\x1b[0m "
                 "%.140s\r\n", rc, ts ? (int)ts3ds_get_status(ts) : -1,
                 reason);
        terminal_write(term, line);
        if (ts) ts3ds_close(ts);
        /* Rich diagnostics only matter while Tailscale is the subject; from
         * here on the terminal belongs to the shell. */
        tailscale_debug_set_runtime(&g_tailscale_debug);
        return NULL;
    }

    {
        uint32_t ip = ts3ds_get_ipv4(ts);
        char line[96];
        snprintf(line, sizeof(line),
                 "\x1b[32mTailscale online:\x1b[0m %u.%u.%u.%u\r\n",
                 (unsigned)((ip >> 24) & 0xff), (unsigned)((ip >> 16) & 0xff),
                 (unsigned)((ip >> 8) & 0xff), (unsigned)(ip & 0xff));
        terminal_write(term, line);
    }
    /* Record the intent, not merely the outcome.  This is what brings the
     * registered node back on the next boot without the auth key — the
     * behaviour that used to be inferred from "tailscale.state exists",
     * and therefore also what a leftover state file used to trigger on
     * cards whose owner had never opted in. */
    if (config_save_tailscale_autostart(CONFIG_PATH) != 0) {
        terminal_write(term,
                       "\x1b[90m(Tailscale is up, but config.ini could not "
                       "record it — it will not auto-start next boot)\x1b[0m"
                       "\r\n");
    }
    g_tailscale = ts;
    return g_tailscale;
}

/* Path of the settings file for machine `m`.  Machine 0 keeps the legacy
 * "settings.ini" so existing installs keep working; machine N gets its own
 * "settings.<N>.ini".  Result is written into the caller-provided buffer. */
static void settings_path_for_machine(int m, char *out, size_t n) {
    if (m <= 0)
        snprintf(out, n, "%s", SETTINGS_PATH);
    else
        snprintf(out, n, "sdmc:/3ds/3dssh/settings.%d.ini", m);
}

/* Connect to machine `idx`, load that machine's project cards, and raise the
 * project picker (when there is something to pick).  Shared by the three entry
 * points: a single-machine startup, the machine picker confirm, and the
 * SELECT reconnect.  Sets *pssh to the new session (or NULL on failure). */
static void connect_and_open(int idx, ssh_client_t **pssh,
                             terminal_t *term, renderer_t *r,
                             C3D_RenderTarget *top, C3D_RenderTarget *bot,
                             softkb_t *kb, keyboard_t *kbd,
                             char *err, int err_sz) {
    /* Refusing silently is what turned "no machine configured" into a
     * screen that looked hung: this is the one call that would have
     * connected, and it wrote nothing at all.  Any caller that gets here
     * with an unusable index now says so on the terminal it was handed. */
    if (idx < 0 || idx >= g_cfg.machine_count) {
        if (pssh) *pssh = NULL;
        /* Both halves of this used to be silent.  A negative index is a
         * caller saying "the picker chose nothing", which is a different
         * problem from an index past the end of the list — the first
         * points at the UI, the second at config.ini — so they get
         * different sentences. */
        if (term) {
            char line[160];
            if (idx >= g_cfg.machine_count)
                snprintf(line, sizeof(line),
                         "\x1b[31mNo machine #%d:\x1b[0m %d configured — edit "
                         "config.ini on the SD card.\r\n",
                         idx, g_cfg.machine_count);
            else
                snprintf(line, sizeof(line),
                         "\x1b[31mNo machine chosen\x1b[0m (index %d) — press "
                         "SELECT to pick one.\r\n", idx);
            terminal_write(term, line);
        }
        return;
    }
    if (!pssh) return;

    g_cfg.selected_machine = idx;
    config_save_selected(CONFIG_PATH, idx);   /* best-effort: remember choice */
    settings_path_for_machine(idx, g_settings_path, sizeof(g_settings_path));

    settings_defaults(&g_loaded_settings);
    settings_load(&g_loaded_settings, g_settings_path);

    /* Push the chosen machine's UI settings into the live surfaces.  The
     * soft keyboard is this app's source of truth for theme / language /
     * mascot / voice limit — main.c syncs the terminals, the keyboard and
     * the recorder off it every frame — so loading the file into
     * g_loaded_settings alone left machine N wearing machine 0's
     * appearance until the next launch.  Worse, the settings page saves by
     * exporting *kb's* values over a freshly loaded file, so the first
     * tweak made while connected to machine N wrote machine 0's
     * preferences into machine N's settings.<N>.ini.
     *
     * softkb_apply_settings() also clears the page's dirty flag, which is
     * unreachable from here: this function is only reached from the machine
     * picker (or the single-machine startup), and the picker eats the
     * frame's input outright, so no settings-page edit can be pending in
     * the same breath. */
    if (kb) softkb_apply_settings(kb, &g_loaded_settings);

    /* Every machine's file is loaded here, so this is the one place that
     * can report a settings file from a NEWER build — for machine N as
     * well as machine 0.  It is loaded (refusing would lose the user's
     * preferences) but settings_save() declines to write it, so say so:
     * otherwise the next page edit looks like it silently did nothing. */
    if (g_loaded_settings.file_version > DSSH_SETTINGS_VERSION) {
        char line[192];
        snprintf(line, sizeof(line),
                 "\x1b[33msettings file is from a newer DSSH (format %d, "
                 "this build reads %d): changes will not be saved.\x1b[0m"
                 "\r\n",
                 g_loaded_settings.file_version, DSSH_SETTINGS_VERSION);
        terminal_write(term, line);
    }

    char banner[160];
    snprintf(banner, sizeof(banner),
             "connecting to \x1b[33m%.48s@%.64s:%d\x1b[0m...\r\n",
             g_cfg.machines[idx].user, g_cfg.machines[idx].host,
             g_cfg.machines[idx].port);
    terminal_write(term, banner);
    render_connecting_frame(top, bot, r, term, kb, kbd);

    /* Tailscale, when this card asks for it.  Deliberately here and not in
     * main()'s prologue: the machine picker (multi-machine cards) or this
     * banner (single-machine cards) is already on screen, so the blocking,
     * bounded dial below is a labelled wait rather than a frozen boot, and
     * a failed bring-up simply means the plain socket. */
    ts3ds *tailscale = tailscale_bring_up(term, r, top, bot, kb, kbd);

    ssh_client_t *ssh = reconnect_ssh(&g_cfg.machines[idx], tailscale, term,
                                      err, err_sz);
    ssh = keychain_bootstrap(ssh, &g_cfg.machines[idx], term, r, kb, kbd,
                             top, bot, err, err_sz);
    *pssh = ssh;

    if (ssh && g_pui &&
        g_loaded_settings.project_count > 0 &&
        g_loaded_settings.show_project_picker) {
        project_ui_open(g_pui, PUI_ENTRY_RUN,
                        g_loaded_settings.selected_project, g_win_cwd[0]);
    }
}

int main(int argc, char *argv[]) {
    char err[256] = {0};
    ssh_client_t *ssh = NULL;
    /* The Tailscale session is g_tailscale, brought up by connect_and_open()
     * rather than here — see the comment above g_tailscale. */
    tailscale_debug_init(&g_tailscale_debug);

    /* ── Graphics & Audio init ── */
    gfxInitDefault();
    audio_init();
    C3D_Init(C3D_DEFAULT_CMDBUF_SIZE);
    C2D_Init(32768);
    C2D_Prepare();
    C3D_RenderTarget *top = C2D_CreateScreenTarget(GFX_TOP,    GFX_LEFT);
    C3D_RenderTarget *bot = C2D_CreateScreenTarget(GFX_BOTTOM, GFX_LEFT);

    /* ── romfs (carries pinyin_dict.bin for M7 IME) ── */
    Result romfs_rc = romfsInit();
    int romfs_ok   = R_SUCCEEDED(romfs_rc);

    /* ── Config ── */
    /* All machines + shared Tailscale config.  File-scope so the machine
     * picker can read it from render_frame(). */
    int config_found = config_load(&g_cfg, CONFIG_PATH);
    /* Default the active-machine settings path to machine 0; the machine
     * picker (or a single-machine direct connect) updates it on choice. */
    settings_path_for_machine(0, g_settings_path, sizeof(g_settings_path));

    /* Seed RNG so the mascot's idle/walk transitions don't repeat across
     * runs.  time(NULL) is fine — we don't need cryptographic randomness. */
    srand((unsigned)time(NULL));

    /* ── Sub-systems ── */
    /* The renderer measures the display, so it comes first: the grid every
     * window starts in is however many cells fit the top panel. */
    renderer_t *r    = renderer_init(top, bot);
    if (r) {
        g_grid_cols = r->top_cols;
        g_grid_rows = r->top_rows;
    }
    terminal_t *term = terminal_init(g_grid_cols, g_grid_rows);
    /* Window 0 is permanent: it is the tab the startup and reconnect banners
     * write to, and its channel is the one ssh_connect_pubkey opens. */
    g_win[0].term  = term;
    g_win[0].state = W_LIVE;
    keyboard_t *kbd  = keyboard_init();
    /* Mascot lives in the bottom row (y=214..239, 26 px tall).  The left
     * info strip (clock / battery) width varies with its content, so the
     * walkable x range is re-measured per frame via mascot_set_bounds()
     * to start right after the text (full row when the text is hidden).
     * Crab is 11 px tall (10-row body + 1-row feet) so
     * y_top = 214 + (26-11)/2 = 221 centers it in the row; the 18-px
     * chick (KUN KUN) shares y_top and sits bottom-aligned (feet at
     * y=238). */
    mascot_t   *mc   = mascot_init(72, MASCOT_ROW_X_MAX, 221);
    /* IME loads later (after the M7 banner pumps); softkb tolerates
     * a NULL ime by falling back to passthrough in CN mode. */
    ime_t      *ime  = NULL;
    softkb_t   *kb   = softkb_init(NULL);
    /* Voice input: physical START toggles record/transcribe.  Server
     * needs `dssh-whisper-shim` on PATH (installed by
     * tools/install_whisper_server.sh).  voice_t is allocated up-front;
     * mic only opens during the RECORDING state. */
    voice_t    *voice = voice_init();
    if (kb && voice) softkb_set_voice(kb, voice);
    /* Custom colours come from a file on the SD card, and it has to be read
     * before settings_load(): settings.ini may say theme_mode = 4, and the
     * first frame must already be the user's palette.  A missing or empty
     * file leaves THEME_CUSTOM byte-identical to the built-in default, so
     * this call is unconditional best-effort, and `trep` is only ever a
     * report — the 自定义 settings row and one banner line show it, nothing
     * else changes. */
    theme_ini_report_t trep;
    theme_ini_load(THEME_INI_PATH, &trep);
    softkb_set_theme_report(kb, &trep);
    /* Load persisted UI settings (theme, mascot, etc.) — best-effort;
     * missing file falls back to softkb defaults.
     *
     * This is the boot-time half of a pair.  softkb — not g_loaded_settings
     * — is what the rest of the app reads for theme, language, mascot and
     * voice limit, so every time the active machine's settings file changes
     * out from under us, the same softkb_apply_settings() has to run again:
     * see connect_and_open(), which does exactly that when the machine
     * picker switches machines. */
    if (kb) {
        dssh_settings_t st;
        settings_defaults(&st);
        settings_load(&st, g_settings_path);
        /* voice_input_mode is a legacy settings.ini field: the M11 redesign
         * collapsed the START/L scheme toggle, and recording is now
         * triggered exclusively by hold-to-talk on R.  Nothing branches on
         * this value — the line below only normalises "auto" (-1) to a
         * concrete number so the round-trip through settings.ini stays
         * stable.  The softkb accessor that used to expose it is gone. */
        if (st.voice_input_mode < 0)
            st.voice_input_mode = 1;
        softkb_apply_settings(kb, &st);
        if (term) terminal_set_theme(term, softkb_theme(kb));
        if (kbd)  keyboard_set_sticky_mode(kbd, softkb_sticky_mode(kb));
        if (voice) voice_set_max_record_sec(voice, softkb_voice_max_sec(kb));
    }
    /* M12: AI-ask modal — pops over the soft keyboard when the user
     * holds R and presses START and a Q&A returns from DeepSeek. */
    ai_modal_t *aim   = ai_modal_init();
    /* The project card page.  Allocated once and reopened by all three
     * entry points; it holds no connection state, so it survives a
     * disconnect/reconnect cycle unchanged. */
    g_pui = project_ui_create();
    g_mui = machine_ui_create();
    /* Same rule again: a bare `goto cleanup` here exits to a blank screen
     * with no clue which subsystem ran out of room, and on a console each of
     * these is a heap allocation.  term may itself be the one that failed,
     * so only write when there is somewhere to write to. */
    if (!term || !r || !kbd || !kb || !mc) {
        if (term) {
            char line[192];
            snprintf(line, sizeof(line),
                     "\x1b[31mStartup failed:\x1b[0m %s%s%s%s did not "
                     "initialise.\r\n",
                     r   ? "" : "renderer ",
                     kbd ? "" : "keyboard ", kb ? "" : "soft-keyboard ",
                     mc  ? "" : "mascot ");
            terminal_write(term, line);
        }
        goto cleanup;
    }

    if (net_init(err, sizeof(err)) != 0) {
        /* The same silent-dead-end family as the machine-count one: a failed
         * socInit() used to drop straight into the idle loop with a blank
         * terminal, no hint, and no way to connect.  On real hardware it has
         * reasons to fail the emulator never exercises — the wireless switch
         * is off, or nwm is not up yet — and every one of those looks from
         * the outside exactly like "DSSH hangs at startup".  Say it.
         *
         * 224, not 200: the two escape sequences and the CJK dash in the
         * second line are 90 bytes on their own, so %.110s of the error code
         * made the worst case 201 into 200 — which cut the trailing "\r\n"
         * at best and the \x1b[0m reset at worst, leaving every line after a
         * failed net_init dim-red. */
        char line[224];
        snprintf(line, sizeof(line),
                 "\x1b[31mNetwork unavailable:\x1b[0m %.110s\r\n"
                 "\x1b[90mDSSH needs Wi-Fi — check the wireless switch.\x1b[0m"
                 "\r\n",
                 err[0] ? err : "unknown error");
        terminal_write(term, line);
        goto idle_loop;
    }

    /* Banner inside the terminal. */
    {
        char vbuf[64];
        snprintf(vbuf, sizeof(vbuf),
                  "\x1b[2m\xe2\x97\x8f\x1b[0m  voice (hold R to record)");
        terminal_write(term, "\x1b[36mDSSH\x1b[0m  "
                             "\x1b[2m\xe2\x97\x8f\x1b[0m  pinyin IME (on-screen 拼/EN)  ");
        terminal_write(term, vbuf);
        terminal_write(term, "\r\n");
    }
    /* The key-hint block is the first thing an English user reads, so it
     * follows the interface language.  Everything past these three lines is
     * terminal history — the shell's own output — and stays untouched. */
    if (softkb_ui_lang(kb)) {
        terminal_write(term,
                       "\x1b[90mSTART+L merges both screens  \xc2\xb7  "
                       "Circle Pad scrolls\x1b[0m\r\n");
        terminal_write(term,
                       "\x1b[90mX+Y \xe2\x96\xb2 new window  \xc2\xb7  "
                       "X+Y \xe2\x96\xbc close  \xc2\xb7  "
                       "X+Y \xe2\x97\x80\xe2\x96\xb6 or L/R switch\x1b[0m\r\n");
        char wline[80];
        snprintf(wline, sizeof(wline),
                 "\x1b[90m(one SSH connection, up to %d windows)\x1b[0m\r\n",
                 MAX_WINDOWS);
        terminal_write(term, wline);
    } else {
        terminal_write(term,
                       "\x1b[90mSTART+L 双屏一体终端（上屏+下屏，再按返回）  ·  "
                       "Circle Pad 滚动\x1b[0m\r\n");
        /* Two tidy lines: the whole hint is ~78 cells on a 66-column screen, and
         * writing it as one string wrapped it mid-phrase. */
        terminal_write(term,
                       "\x1b[90mX+Y ▲ 新窗口  ·  X+Y ▼ 关闭窗口  ·  "
                       "X+Y ◀▶ 或 L/R 切换\x1b[0m\r\n");
        char wline[80];
        snprintf(wline, sizeof(wline),
                 "\x1b[90m（同一条 SSH 连接，最多 %d 个窗口）\x1b[0m\r\n",
                 MAX_WINDOWS);
        terminal_write(term, wline);
    }
    /* Which build is installed.  Nothing else on the machine says so — the CIA
     * carries no visible version and the SD card holds no version file — so a
     * bug report could not be matched to a commit without this.  Its own line
     * because the header line is already ~67 cells on a 66-column screen; a
     * `git describe` string does not fit beside it. */
    {
        char verline[80];
        snprintf(verline, sizeof(verline),
                 "\x1b[90mDSSH %.48s\x1b[0m\r\n", DSSH_VERSION);
        terminal_write(term, verline);
    }
    /* One dim line about theme.ini, and only when it has something to say.
     * With no file and a built-in theme chosen — everyone who has never heard
     * of this feature — the boot screen stays exactly as it was.  But a file
     * that exists and is being ignored is a visible difference with no other
     * signal, and so is 自定义 with nothing behind it. */
    if (trep.status != THEME_INI_MISSING ||
        softkb_theme(kb) == THEME_CUSTOM) {
        char what[112], line[136];
        theme_ini_describe(&trep, softkb_ui_lang(kb), what, sizeof(what));
        if (what[0]) {
            snprintf(line, sizeof(line), "\x1b[90m%s\x1b[0m\r\n", what);
            terminal_write(term, line);
        }
    }
    if (romfs_ok) {
        terminal_write(term, "loading pinyin dictionary...\r\n");
    } else {
        terminal_write(term, "\x1b[33mromfs init failed — IME unavailable\x1b[0m\r\n");
    }

    /* ── On-card state notices ────────────────────────────────────────
     * The launch screen is the only channel a 3DS app has for telling the
     * user that the card is not in the shape this build expects, and each
     * of these changes what the app will do — or refuse to do — from here
     * on, so none of them may be silent.  None of them is an error either:
     * the app runs in every case, which is why they are dim, not red.
     *
     * The matching notice for a per-machine settings file lives in
     * connect_and_open(), which is the only place that loads one. */
    if (config_file_is_newer(&g_cfg)) {
        char line[200];
        snprintf(line, sizeof(line),
                 "\x1b[33mconfig.ini is from a newer DSSH (format %d, this "
                 "build reads %d): loaded, but never rewritten.\x1b[0m\r\n",
                 g_cfg.file_version, DSSH_CONFIG_VERSION);
        terminal_write(term, line);
    } else if (!config_found) {
        terminal_write(term,
                       "\x1b[90mno config.ini — using built-in defaults; "
                       "edit sdmc:/3ds/3dssh/config.ini\x1b[0m\r\n");
    }

    /* Machines the file names but the app is ignoring, because a gap in the
     * indexing stopped the count (see config_load).  This one has to be
     * said: the alternative is that the user's third machine simply is not
     * there, and "my config does not list it" is the one wrong conclusion
     * they cannot check without pulling the card. */
    if (g_cfg.machines_after_gap > 0) {
        char line[256];
        snprintf(line, sizeof(line),
                 "\x1b[33mconfig.ini numbers a machine past a gap: host_%d "
                 "is missing.\x1b[0m\r\n"
                 "\x1b[90mMachines count from 0 with no gap — %d configured "
                 "after that are not listed. Edit config.ini.\x1b[0m\r\n",
                 g_cfg.machine_count, g_cfg.machines_after_gap);
        terminal_write(term, line);
    }

    /* Tailscale is deliberately NOT brought up here.  It used to be, and
     * it was the first thing a launch did after the banners: a blocking
     * dial (30 s before DSSH_TAILSCALE_CONNECT_MS existed) on the only
     * thread, before the machine picker could be drawn, and a failure sent
     * the app straight to the idle loop — skipping the picker AND the SSH
     * connect, leaving a terminal that could never come up.  A card that
     * merely had a tailscale.state file left over from an older build got
     * all of that without ever having asked for Tailscale.  It now runs in
     * connect_and_open(), after the picker, and cannot fail the launch. */

    /* Pump one frame so the user sees the loading banner during the
     * (synchronous, ~5s) dict read.  The bottom screen still has the
     * keyboard rendered — the badge and mascot work normally. */
    render_connecting_frame(top, bot, r, term, kb, kbd);

    /* Load the pinyin dict (~9 MB).  Failure here is non-fatal — we
     * just leave ime NULL and softkb degrades CN mode to passthrough. */
    if (romfs_ok) {
        ime = ime_init("romfs:/pinyin_dict.bin");
        g_ime = ime;   /* win_focus() clears a half-typed syllable on tab switch */
        if (ime) {
            softkb_set_ime(kb, ime);
            keyboard_set_ime(kbd, ime);
            terminal_write(term, "\x1b[32mdictionary loaded.\x1b[0m\r\n");
        } else {
            terminal_write(term, "\x1b[31mdictionary load failed — IME disabled\x1b[0m\r\n");
        }
    }

    /* Nothing to connect to.
     *
     * This used to fall straight through to connect_and_open(0, ...), which
     * returns immediately once the index is past machine_count — writing
     * nothing, opening nothing, and leaving the user on a boot banner that
     * never changes again.  A card with no config.ini at all, one the app
     * cannot read, or one whose only host line is empty therefore looked
     * exactly like a hang: the machine picker is only opened when
     * machine_count > 1, so there was not even a page to land on.  Say what
     * is wrong instead; the fix is a file on the card, and the user cannot
     * guess that from a blank terminal. */
    if (g_cfg.machine_count == 0) {
        terminal_write(term,
                       "\x1b[31mNo SSH machine is configured.\x1b[0m\r\n");
        terminal_write(term, config_found
            ? "\x1b[90mconfig.ini was read, but it has no usable host — every "
              "host_N line is missing or empty.\x1b[0m\r\n"
            : "\x1b[90mconfig.ini could not be read (missing, or the card "
              "is not mounted).\x1b[0m\r\n");
        terminal_write(term,
                       "\x1b[90msee sdmc:/3ds/3dssh/config.ini.example — DSSH "
                       "needs a host_N line to connect.\x1b[0m\r\n");
        goto idle_loop;
    }

    /* Multiple machines configured: let the user pick one before connecting.
     * The picker is serviced by the idle loop below; choosing a machine there
     * calls connect_and_open() and raises the project page.  A single
     * machine connects directly, preserving the pre-multi-machine start-up
     * behaviour. */
    if (g_cfg.machine_count > 1) {
        machine_ui_open(g_mui, &g_cfg, g_cfg.selected_machine,
                        softkb_ui_lang(kb));
        goto idle_loop;
    }
    connect_and_open(0, &ssh, term, r, top, bot, kb, kbd,
                     err, sizeof(err));

    /* NOTE: the selected machine's passphrase / macos_keychain_password
     * intentionally stay in memory — the SELECT-key reconnect path
     * re-authenticates with them.  They are wiped by clear_secret() in the
     * cleanup path at exit. */

idle_loop:
    {
        char rbuf[READ_BUFSZ];

        /* ALERT triggers (mascot raises the red ✕):
         *
         *  - Interactive-stall (5 s): the focused window sent bytes more
         *    recently than it received any reply, and nothing came back for
         *    5 s.  Means the user is actively waiting and not getting
         *    through.  Per-window on purpose: a busy background shell must
         *    not mask a foreground that really did stop answering.
         *
         *  - Hard disconnect: ssh_read_slot returned -2 — libssh2 detected
         *    the socket is dead, which takes every channel with it.  (-1 is
         *    something else: only that one window's shell exited.)  Once
         *    this fires we never recover in-session (no auto-reconnect
         *    logic), so the alert stays on until the user reconnects with
         *    SELECT or relaunches DSSH.  Replaces the old "[disconnected]"
         *    terminal banner. */
        const int STALL_TX_NORX_S = 5;
        win_touch_all();
        int    stall_alert = 0;
        int    ssh_dead    = ssh ? 0 : 1;
        /* START+L toggles "dual-screen one-terminal" mode: both physical screens
         * become one 66×40 terminal grid (top 20 rows + bottom 20 rows). */
        int    dual_term = 0;
        /* static, unlike its neighbours: this one is a *timer* that has to
         * outlive the frame that set it.  As a plain automatic it was
         * re-zeroed at the top of every iteration, so the "wait a second
         * before retrying a failed settings write" below never waited for
         * anything — a busy or missing SD card got a write attempt every
         * single frame, which is exactly what the cooldown exists to stop. */
        static int settings_save_cooldown = 0;
        /* R hold-to-talk: r_take latches "this take came from R" so the
         * release edge can find it and end + send.  Presses that didn't
         * manage to start recording leave it 0, so their release is a no-op.
         * (Was `l_take` while L was the voice key — R took that role when
         * L was released to become the START+L dual-screen modifier.) */
        int    r_take = 0;
        /* Which D-pad directions armed an X+Y chord.  Swallowed until they are
         * physically up, so keyboard.c never also sends a held arrow on the
         * frame a window opens, closes or gets focused. */
        u32    chord_dpad_swallow = 0;

        while (aptMainLoop()) {
            if (g_tailscale &&
                ts3ds_get_status(g_tailscale) == TS3DS_STATUS_ONLINE)
                ts3ds_poll(g_tailscale);
            hidScanInput();
            u32 down = hidKeysDown();
            u32 held = hidKeysHeld();
            /* Physical key state, captured before any surface steals bits
             * out of `held`.  `held` is the *consumable* mask: the settings
             * page strips the keys it uses, the X+Y chords strip their
             * triggers, and the project page zeroes it outright for the frame
             * it ate.  Anything asking "is this key still down?" must read
             * this one instead — a release edge read off a mask another
             * surface just emptied fires while the user is still holding the
             * key.  (That was the R hold-to-talk bug: opening the project
             * page mid-take shipped the recording truncated and then missed
             * the real release, because r_take had already been dropped.) */
            u32 held_phys = held;
            circlePosition cpad;

            /* Hardware ABXY key sound — single upstream tap so every
             * downstream consumer (modal / settings / projects editor /
             * chord swallows) still gets the audio cue.  Independent of
             * input semantics: A stays "Enter-like", Y stays Ctrl, X
             * stays Alt, B stays Esc-like.  With the mascot enabled the
             * species-tinted FUNC voice fires (蟹/鸡/菌/哔哔/哞/汪);
             * with the mascot off audio_play_key()'s mascot_enabled=0
             * branch falls back to the base click — same fallback as
             * softkb's Enter/Backspace path.  A press that's already
             * ringing (FUNC slot busy) is dropped by ndsp so we never
             * stack a chicken on top of itself. */
            if (down & (KEY_A | KEY_B | KEY_X | KEY_Y)) {
                int    abxy_mascot_on = softkb_mascot_enabled(kb);
                mascot_species_t abxy_sp = softkb_mascot_species(kb);
                audio_play_key(AUDIO_KEY_FUNC, abxy_mascot_on, abxy_sp);
            }

            /* The project card page owns the whole keypad and both screens
             * while it is up — it is a settings-style page but lives
             * outside the settings framework because its rows are cards,
             * not scalar toggles.  It is serviced further down, after the
             * window chords, so a chord press cannot spawn a window behind
             * it. */
            hidCircleRead(&cpad);

            /* Touch geometry for this frame, read once here: the project
             * page hit-tests its own widgets against these, and the soft
             * keyboard block further down reuses them.  hidTouchRead
             * already reports bottom-screen pixels. */
            int touch_pressed = (held & KEY_TOUCH) ? 1 : 0;
            int tx = -1, ty = -1;
            if (touch_pressed) {
                touchPosition tp;
                hidTouchRead(&tp);
                tx = tp.px; ty = tp.py;
            }
            int touch_down = (down & KEY_TOUCH) ? 1 : 0;

            /* The dual-screen settings page owns the whole keypad while
             * open (↑↓ select, ←→/A adjust, B close).  Strip every owned
             * bit from both masks up front so the same press does not
             * also start hold-to-talk (R), send arrows to the remote,
             * start an AI-ask take (R+START) or flip the dual-screen view
             * (START+L).
             * The AI modal wins over settings when both would be up. */
            int modal_open = ai_modal_visible(aim);
            /* Two different questions, two different predicates.  `modal_open`
             * answers "is the panel painted" and guards *layout* precedence —
             * it must stay 1 through the fade-out so the project page cannot
             * pop up over a panel the user can still see.  `modal_capture`
             * answers "does the modal own the keypad" and stops at the close,
             * because ai_modal_close() is the moment the user dismissed it:
             * gating input on `modal_open` left every key, the soft keyboard
             * and all touch dead for the 12-frame fade-out (~0.2 s). */
            int modal_capture = ai_modal_captures_input(aim);
            /* Read before the settings handler below: the project page
             * borrows the soft keyboard for text entry, so while it is up
             * the ⚙ badge is on screen (main.c draws softkb_draw on the
             * bottom) but the settings page it opens would paint nowhere —
             * the pui branches in render_frame win both screens.  An open
             * but invisible settings page still owned the whole keypad and
             * still wrote its dirty flag back to settings.ini. */
            int pui_up = project_ui_visible(g_pui);
            int mui_up = g_mui && machine_ui_visible(g_mui);
            /* The invariant, held every frame rather than only at the badge:
             * settings_open is a mode of the keyboard-as-input-surface, so
             * it is 0 whenever another page has rented that surface.  That
             * covers the AI-ask modal too — it swallows taps while it
             * captures, but a fresh tap during its 12-frame fade-out still
             * falls through to softkb_touch(). */
            if (pui_up || modal_open || mui_up) softkb_leave_settings(kb);
            u32 set_keys = (modal_capture || pui_up || mui_up) ? 0u
                                         : softkb_settings_keys(kb, down, held);
            if (set_keys) {
                down &= ~set_keys;
                held &= ~set_keys;
            }

            /* ── Window chords ──
             * X+Y+▲ opens a window on the same SSH session, X+Y+▼ closes the
             * one you are looking at, and X+Y+◀ / X+Y+▶ step to the previous /
             * next one (wrapping) — X+Y+L / X+Y+R do the same thing, for the
             * hands that are already on the shoulder buttons.  ▲/▼ read as
             * spawn / dismiss and ◀/▶ as back / forward; all four are physical
             * on every model, unlike ZL/C-Stick, which is why the START+L
             * dual-screen toggle uses L (every model has L) rather than ZL.
             *
             * The steal removes the trigger key *and* both modifiers: left in
             * `held`, keyboard.c's sticky logic would latch Alt/Ctrl and leak
             * ESC+char into the shell afterwards.  Dropping L also keeps
             * hold-to-talk from arming on this press, and dropping R keeps
             * the EN/CN IME toggle from flipping. */
            u32 steal = 0;
            int chord = !modal_capture && !softkb_settings_open(kb) &&
                        !pui_up && !mui_up &&
                        (held & KEY_X) && (held & KEY_Y);
            if (chord && (down & KEY_DUP)) {
                win_create(ssh);
                steal = KEY_X | KEY_Y | KEY_DUP;
                chord_dpad_swallow |= KEY_DUP;
            } else if (chord && (down & KEY_DDOWN)) {
                win_close_focused(ssh);
                steal = KEY_X | KEY_Y | KEY_DDOWN;
                chord_dpad_swallow |= KEY_DDOWN;
            } else if (chord && (down & KEY_DLEFT)) {
                win_focus_rel(-1);
                steal = KEY_X | KEY_Y | KEY_DLEFT;
                chord_dpad_swallow |= KEY_DLEFT;
            } else if (chord && (down & KEY_DRIGHT)) {
                win_focus_rel(1);
                steal = KEY_X | KEY_Y | KEY_DRIGHT;
                chord_dpad_swallow |= KEY_DRIGHT;
            } else if (chord && (down & KEY_L)) {
                win_focus_rel(-1);
                steal = KEY_X | KEY_Y | KEY_L;
            } else if (chord && (down & KEY_R)) {
                win_focus_rel(1);
                steal = KEY_X | KEY_Y | KEY_R;
            }
            /* Keep swallowing those directions until they are physically
             * released: on the frame after a chord the D-pad still reads held,
             * and keyboard.c would emit a stray arrow — and keep repeating it,
             * since its auto-repeat runs off `held` not the press edge.  Per
             * bit, so sliding ▲→◀ cannot uncover the arrow still held down. */
            chord_dpad_swallow &= held_phys;
            if (chord_dpad_swallow) steal |= chord_dpad_swallow;
            if (steal) {
                down &= ~steal;
                held &= ~steal;
            }

            /* ── Project card page ──
             * Serviced after the chords so a card list that is up cannot
             * be undercut by X+Y+▲ spawning a window behind it.  The page
             * is the only consumer that reads the raw touch coordinates
             * itself; the soft keyboard sees them only while the page is
             * borrowing it for text entry, and even then not for the
             * gesture that opened the sub-mode (project_ui_keyboard_armed)
             * — otherwise the tap that chose a form row would also press
             * whatever key sits under the finger. */
            /* ── Machine picker ──
             * Serviced before the project page (the two are never up at once).
             * A / tap connects to the chosen machine and raises the project
             * page; B just closes; X (or a tap on a row's ✎ strip) opens the
             * rename field, which borrows the soft keyboard exactly as the
             * project page does.  Eats the frame so none of it can also reach
             * the shell, the IME or the voice triggers. */
            if (mui_up) {
                const char *mui_kt = NULL;
                if (machine_ui_wants_keyboard(g_mui)) {
                    /* Not for the gesture that opened the field
                     * (machine_ui_keyboard_armed) — otherwise the tap on the
                     * ✎ would also press whatever key sits under the finger. */
                    int armed = machine_ui_keyboard_armed(g_mui);
                    mui_kt = softkb_touch(kb, kbd,
                                          armed ? tx : -1, armed ? ty : -1,
                                          touch_pressed);
                }
                int run_idx = -1;
                int rc = machine_ui_tick(g_mui, &g_cfg, down, held, mui_kt,
                                         tx, ty, touch_pressed, touch_down,
                                         &run_idx);
                if (rc == MUI_ACT_CONNECT) {
                    machine_ui_close(g_mui);
                    connect_and_open(run_idx, &ssh, term, r, top, bot, kb,
                                     kbd, err, sizeof(err));
                    if (ssh) {
                        ssh_dead = 0;
                        stall_alert = 0;
                        mascot_set_alert(mc, 0);
                        mascot_celebrate(mc);
                        win_touch_all();
                        g_win[0].state = W_LIVE;
                        g_win[0].dirty = 0;
                        win_focus(0);
                    } else {
                        mascot_sadden(mc);
                        terminal_write(term, softkb_ui_lang(kb)
                            ? "\x1b[31mConnection failed; press SELECT to "
                              "retry.\x1b[0m\r\n"
                            : "\x1b[31m连接失败；按 SELECT 重试。\x1b[0m\r\n");
                    }
                } else if (rc == MUI_ACT_CANCEL) {
                    /* Cancelling leaves no session at all — this page is the
                     * only thing that opens one.  Without a word here the
                     * user is left with the mascot's ✕ and no way to learn
                     * that SELECT brings the picker back: the
                     * "Press SELECT to reconnect" banner further down never
                     * fires, because it is driven by a session dying and
                     * this one never existed. */
                    machine_ui_close(g_mui);
                    terminal_write(term, softkb_ui_lang(kb)
                        ? "\x1b[33mNo machine selected \xe2\x80\x94 press "
                          "SELECT to pick one.\x1b[0m\r\n"
                        : "\x1b[33m未选择机器 \xe2\x80\x94 按 SELECT 重新选择。"
                          "\x1b[0m\r\n");
                } else if (rc == MUI_ACT_RENAMED) {
                    /* The page hands the name out rather than writing it:
                     * main.c owns both the live config and the file.  Applied
                     * to g_cfg first so the list redraws this frame, then
                     * persisted best-effort — a name is a label, and failing
                     * to save one must not cost the user anything else. */
                    int ri = machine_ui_renamed_index(g_mui);
                    if (ri >= 0 && ri < g_cfg.machine_count) {
                        snprintf(g_cfg.machines[ri].name,
                                 sizeof(g_cfg.machines[ri].name), "%s",
                                 machine_ui_renamed_name(g_mui));
                        config_save_machine_name(CONFIG_PATH, ri,
                                                 g_cfg.machines[ri].name);
                    }
                }
                down = 0;
                held = 0;
            }

            const char *pui_kt = NULL;
            if (pui_up) {
                if (project_ui_wants_keyboard(g_pui)) {
                    int armed = project_ui_keyboard_armed(g_pui);
                    pui_kt = softkb_touch(kb, kbd,
                                          armed ? tx : -1, armed ? ty : -1,
                                          touch_pressed);
                }
                int run_idx = -1;
                pui_act_t act = project_ui_tick(g_pui, &g_loaded_settings, ssh,
                                                down, held, pui_kt,
                                                tx, ty, touch_pressed,
                                                touch_down, &run_idx);
                if (act == PUI_ACT_RUN && run_idx >= 0) {
                    project_run(ssh, g_focus, &g_loaded_settings, run_idx);
                }
                /* The page ate this frame.  Zeroing the masks is what keeps
                 * a card tap from also reaching the shell, the IME, the
                 * voice triggers and the START+L view toggle — all of
                 * which read `down`/`held` further down. */
                down = 0;
                held = 0;
            }
            /* Retry the project page's pending settings write — deliberately
             * OUTSIDE the `if (pui_up)` above.  A failed write (busy or
             * missing card) keeps ui->dirty set and arms the cooldown, but
             * the page can be closed with B long before those 60 frames
             * elapse; with the retry living inside the page-up branch the
             * flag then sat there for the rest of the session and the edit
             * was silently lost.  Order matters: this runs BEFORE the softkb
             * block further down, which re-reads the file and overlays its
             * own fields, so a UI change saved in the same frame survives
             * this whole-struct write. */
            if (project_ui_dirty(g_pui) && settings_save_cooldown == 0) {
                if (!project_settings_save(g_pui, kb))
                    settings_save_cooldown = 60;
            }
            /* The page went down this frame — by B/START, or because a card
             * was just run.  Dropping the soft keyboard's 项目 gate on the
             * *transition* rather than on PUI_ACT_CLOSED alone means no exit
             * path can leave it latched: a latched gate raises the page
             * again on the very next frame and there is then no way to
             * close it.  Runs before the settings raise below, so the clear
             * is what the raise sees. */
            if (g_pui_was_up && !project_ui_visible(g_pui)) {
                softkb_projects_close(kb);
                if (touch_pressed) g_touch_swallow = 1;
            }
            g_pui_was_up = project_ui_visible(g_pui);

            /* A card chosen for a window whose shell channel is still
             * opening is parked in g_pending_cmd; ship it the frame the
             * slot goes live.  This is what makes "X+Y▲ then pick a card"
             * land in the right shell instead of being dropped. */
            for (int i = 0; i < MAX_WINDOWS; i++) {
                if (!g_pending_cmd[i][0]) continue;
                if (ssh_slot_state(ssh, i) != SSH_SLOT_LIVE) continue;
                ssh_write_slot(ssh, i, g_pending_cmd[i],
                               (int)strlen(g_pending_cmd[i]));
                g_pending_cmd[i][0] = 0;
            }

            /* A window the chord just created raises the page for its own
             * shell — the point of the feature is that different windows
             * can run different tools in different directories, so the
             * card has to be chosen per window, not once per session.
             *
             * Deliberately not gated on project_count: with no cards yet
             * the page's empty state is the shortest path to making one,
             * which is exactly what a first-run user needs. */
            if (g_win_just_created >= 0 &&
                !modal_open && !project_ui_visible(g_pui) && g_pui) {
                project_ui_open(g_pui, PUI_ENTRY_RUN,
                                g_loaded_settings.selected_project,
                                g_win_cwd[g_win_just_created]);
                g_win_just_created = -1;
            }

            /* 设置 → 项目.  The settings row only flips a flag in softkb;
             * this is the side that actually raises the page, which is why
             * all three entry points end up in the same object. */
            if (!modal_open && !project_ui_visible(g_pui) && g_pui &&
                softkb_projects_open(kb)) {
                project_ui_open(g_pui, PUI_ENTRY_SETTINGS,
                                g_loaded_settings.selected_project,
                                g_win_cwd[g_focus]);
            }

            /* One derivation point, after the focus may have just moved:
             * every use of `term` below (input, local banners, rendering)
             * means "the focused window's terminal".  Same place to give it
             * the grid the user is looking at, so a window tabbed onto is
             * never drawn at a stale size. */
            term = focus_term();
            win_apply_view(ssh, g_focus);
            tailscale_debug_flush(&g_tailscale_debug, term);

            /* Synchronize live settings */
            poll_battery();
            keyboard_set_sticky_mode(kbd, softkb_sticky_mode(kb));
            keyboard_set_repeat_style(kbd, softkb_repeat_style(kb));
            /* Every window, not just the focused one: a theme switch remaps
             * the colors already on screen, so a background shell that kept
             * the old palette would flash it the moment the user tabbed over.
             */
            if (terminal_get_theme(term) != softkb_theme(kb)) {
                for (int i = 0; i < MAX_WINDOWS; i++)
                    if (g_win[i].term)
                        terminal_set_theme(g_win[i].term, softkb_theme(kb));
            }
            if (voice && voice_get_max_record_sec(voice) != softkb_voice_max_sec(kb)) {
                voice_set_max_record_sec(voice, softkb_voice_max_sec(kb));
            }
            /* Persist settings when dirty (best-effort SD write, throttled
             * on failure to avoid per-frame spam if the card is busy).
             *
             * softkb_export_settings() now overlays onto a caller-loaded
             * struct rather than re-seeding from defaults, so the [projects]
             * section the editor wrote earlier survives a UI tweak here.
             * We always reload the file before exporting so a manual edit
             * on the SD card between saves is not clobbered either. */
            if (softkb_settings_dirty(kb)) {
                if (settings_save_cooldown == 0) {
                    dssh_settings_t st;
                    settings_defaults(&st);
                    settings_load(&st, g_settings_path);
                    softkb_export_settings(kb, &st);
                    if (settings_save(&st, g_settings_path) == 0) {
                        softkb_clear_settings_dirty(kb);
                    } else {
                        settings_save_cooldown = 60;
                    }
                } else {
                    settings_save_cooldown--;
                }
            } else if (settings_save_cooldown > 0) {
                /* Settings page has nothing pending, but a cooldown the
                 * project page started still has to tick down.  Snapping it
                 * straight to 0 here used to make that one last a single
                 * frame, so a failing card edit was retried every frame. */
                settings_save_cooldown--;
            }

            /* M12 — AI-ask modal swallows input.  When the modal is up
             * (or animating in/out), suppress all routing to softkb /
             * keyboard / IME / mascot.  A=keep history, B=clear, touch
             * anywhere on the bottom screen=clear. */

            /* Dual-screen one-terminal mode toggle (START+L).  This is a pure
             * view switch, so it works even while a modal is up: entering
             * renegotiates the PTY to 66×40 (the shell repaints into both
             * screens as one continuous grid), leaving shrinks it back to
             * 66×20.  The terminal widget resizes regardless of link state;
             * ssh_set_pty_size_slot is a safe no-op while disconnected.  Blocked
             * while the settings page owns the screens (belt and suspenders
             * — the key steal above strips START+L).
             *
             * M11.2: ZR was an earlier trigger but got retired to keep the
             * key surface model-uniform across hardware (ZR doesn't exist
             * on original 3DS / 2DS; promoting a second trigger would
             * create two ways to do the same thing and require per-model
             * documentation).  START+L is the single supported entry point
             * and works on every 3DS-family model.
             *
             * Note: the X+Y+L window chord above steals KEY_L out of
             * `held`, so a START+L pressed while X+Y are also held
             * won't trigger this — the chord "wins" and switches
             * windows.  That's intentional: chords compose by
             * extending the held mask, not by chaining recognisers. */
            int dual_toggle = 0;
            if ((down & KEY_START) && (held & KEY_L) &&
                !softkb_settings_open(kb)) {
                /* Disambiguate from START+R (AI-ask): require L held
                 * and R NOT held.  See main.c voice block for the
                 * START+R path. */
                if (!(held & KEY_R)) dual_toggle = 1;
            }
            if (dual_toggle) {
                dual_term = !dual_term;
                g_grid_cols = r->top_cols;
                g_grid_rows = r->top_rows * (dual_term ? 2 : 1);
                /* Applied to the focused window in this same frame: `dual_term`
                 * is also what tells the renderer to draw 40 rows, so the one
                 * window on screen must be 40 rows before it is drawn.  The
                 * other windows keep their old geometry and catch up when the
                 * user tabs to them — resizing them now would SIGWINCH four
                 * TUIs at once and light up every ● as fake unread output. */
                win_apply_view(ssh, g_focus);
            }

            if (modal_capture) {
                if (down & KEY_A) {
                    voice_ai_close_keep(voice);
                    ai_modal_close(aim);
                }
                if (down & KEY_B) {
                    voice_ai_close_clear(voice);
                    ai_modal_close(aim);
                }
            } else {
                /* Voice triggers (M11 redesign):
                 *   R held           → voice-IME recording, hold-to-talk
                 *   R held + START   → AI-ask voice modal
                 *   START alone      → no voice action (START used to be
                 *                      the tap-toggle trigger; that scheme
                 *                      was dropped in favour of the single
                 *                      R hold-to-talk entry point — every
                 *                      model has R, no mode toggle needed)
                 *   L                → idle (used by START+L dual-screen
                 *                      toggle further down — keep clear)
                 *
                 * `r_take` mirrors the old `l_take` latch: 1 while the
                 * current take was opened by an R press, so the release
                 * edge can find it and end + send the take.  Presses
                 * that didn't manage to start a take leave it 0, so
                 * their release is a no-op. */
                if (voice_state(voice) == VOICE_IDLE) g_voice_slot = g_focus;
                /* START+R → AI-ask.  Disarm the R hold-to-talk take on
                 * the same frame so the AI cycle owns the rest of the
                 * press (and R's release at the end of an AI take does
                 * not also flip us into plain IME voice). */
                if ((down & KEY_START) && (held & KEY_R)) {
                    r_take = 0;
                    voice_ai_toggle(voice, ssh);
                } else {
                    /* R — voice-IME recording, pure hold-to-talk.  The
                     * press starts the take, the release ends and sends
                     * it.  No tap behaviour: pressing R while the
                     * previous take is still transcribing or typing does
                     * nothing (the START+R chord above is the only way
                     * to cancel an upload in flight — but only as a
                     * promote-to-AI, never as a plain cancel).  The
                     * ai-cycle guard on the release side is what keeps
                     * letting go of R from cutting an AI take short. */
                    if (down & KEY_R) {
                        if (voice_state(voice) == VOICE_IDLE) {
                            voice_toggle(voice, ssh);
                        }
                        r_take = (voice_state(voice) == VOICE_RECORDING);
                    } else if (r_take && !(held_phys & KEY_R)) {
                        r_take = 0;
                        if (voice_state(voice) == VOICE_RECORDING &&
                            !voice_in_ai_cycle(voice)) {
                            voice_toggle(voice, ssh);
                        }
                    }
                    /* The release test reads the *physical* mask
                     * (held_phys), not `held`: the settings page and the
                     * X+Y+R chord strip KEY_R out of `held`, and the
                     * project page zeroes `held` outright for the frame it
                     * ate.  Read off `held`, all three looked like a
                     * release and shipped the take mid-word while the user
                     * was still holding R, and the real release then found
                     * r_take already 0.  Arming stays on the down edge,
                     * which is what keeps a stolen press from *starting*
                     * a take. */
                }
            }

            /* Per-frame voice tick — drives recording cap, async aux
             * channel write/eof/read, and forwards the transcribed
             * Chinese text to the main SSH channel via ssh_write.  Also
             * transitions us into VOICE_AI_SHOWING after a successful
             * AI transcribe; we open the modal once that happens.
             *
             * voice.c writes through the session's *write slot* (it knows
             * nothing about windows), so pin it for the whole cycle: tabbing
             * over must not re-target the shell that receives the text. */
            voice_state_t prev_state = voice_state(voice);
            int voice_writes = (prev_state == VOICE_RECORDING ||
                                prev_state == VOICE_TRANSCRIBING ||
                                prev_state == VOICE_TYPING);
            ssh_set_write_slot(ssh, voice_writes ? g_voice_slot : g_focus);
            voice_tick(voice, ssh);
            voice_state_t cur_state = voice_state(voice);
            if (prev_state != VOICE_AI_SHOWING &&
                cur_state == VOICE_AI_SHOWING) {
                ai_modal_open(aim,
                              voice_ai_question(voice),
                              voice_ai_answer(voice));
            }
            ai_modal_tick(aim);

            /* Voice ↔ mascot link (level-driven, every frame).  RECORDING
             * → mic pose; TRANSCRIBING → ? pose; TYPING → no static pose
             * (the per-glyph mascot_type_kick below drives the typing
             * peck instead, same animation the soft keyboard uses).  We
             * must drive this every frame rather than on state edges,
             * because voice_toggle() (IDLE→RECORDING) and begin_transcribe()
             * (RECORDING→TRANSCRIBING) run inside the key-handler /
             * voice_tick before we sample prev_state, so an edge-triggered
             * link would sample prev==cur and skip the exact transition
             * we need to catch. */
            int rec  = (cur_state == VOICE_RECORDING);
            int thk  = (cur_state == VOICE_TRANSCRIBING);
            if (rec)      { mascot_set_recording(mc, 1); mascot_set_thinking(mc, 0); }
            else if (thk) { mascot_set_thinking(mc, 1); mascot_set_recording(mc, 0); }
            else          { mascot_set_recording(mc, 0); mascot_set_thinking(mc, 0); }

            /* Voice TYPING streams glyphs straight to ssh_write inside
             * voice.c, bypassing send_to_ssh — so the per-glyph typing
             * kick wired into send_to_ssh wouldn't fire.  Latch on the
             * voice side, consume here and kick manually so the crab
             * pecks in sync with each streamed character. */
            if (cur_state == VOICE_TYPING && voice_consume_typed(voice)) {
                mascot_type_kick(mc);
            }

            /* ── SSH receive (one pass per window) ──
             * keepalive is session-wide; the reads are not.  The focused tab
             * goes first with the bigger budget because its latency is what
             * the user is watching, then every background tab gets a turn —
             * they MUST be drained too, since an unread channel fills the
             * server's window and the remote TUI blocks on SSH flow control.
             * Bytes left over because a frame's budget ran out stay in the
             * socket buffer and catch up the moment the user tabs over. */
            if (ssh && ssh_is_connected(ssh)) {
                ssh_keepalive_tick(ssh);
                int session_dead =
                    win_pump(ssh, g_focus, rbuf, FOCUS_RX_CHUNKS, kb, 1) == -2;
                for (int i = 0; i < MAX_WINDOWS && !session_dead; i++) {
                    if (i == g_focus) continue;
                    if (win_pump(ssh, i, rbuf, BG_RX_CHUNKS, kb, 0) == -2)
                        session_dead = 1;
                }
                if (session_dead) {
                    /* Hard disconnect.  Abort any in-flight voice work
                     * (its aux channel dies with the session), tear down
                     * the session, mark it dead so the mascot raises ✕,
                     * and show a one-shot red banner telling the user how
                     * to recover (SELECT reconnect).  Only fires on the
                     * 0→1 transition of ssh_dead — no per-frame spam.
                     *
                     * The project page holds an aux channel of its own (the
                     * `pwd` probe) and must go the same way: ssh_disconnect
                     * frees the LIBSSH2_SESSION, so a later ssh_aux_close
                     * would call libssh2_channel_* on freed memory.  Closing
                     * the page also lets the banner below be seen — while the
                     * page is up it covers both screens. */
                    if (g_pui) project_ui_close(g_pui);
                    voice_abort(voice);
                    ssh_disconnect(ssh);
                    ssh = NULL;
                    ssh_dead = 1;
                    /* Every shell channel went with the session; only
                     * window 0's terminal survives to show the banner. */
                    win_prune();
                    term = focus_term();
                    terminal_write(term,
                        "\r\n\x1b[31mConnection lost\r\n\x1b[0m"
                        "\x1b[33mPress SELECT to reconnect\r\n\x1b[0m");
                } else {
                    /* A background tab closing (or the focused one) can move
                     * the focus mid-frame — the renderer must follow, and the
                     * window it lands on may still be at the grid it had when
                     * the user last looked at it. */
                    term = focus_term();
                    win_apply_view(ssh, g_focus);
                }
            }

            /* ALERT = hard disconnect, OR active interactive stall on the
             * focused window.  Background shells keep talking on their own
             * schedule, so their traffic must not be allowed to mask (or
             * fake) a foreground that really stopped answering.
             * While voice input is active (RECORDING/TRANSCRIBING/TYPING)
             * the user is talking to the mic, not typing, so the SSH
             * channel going quiet is expected.  Skip the stall detector
             * entirely during voice so it can neither raise nor lower
             * the alert — the crab is owned by the voice-state link
             * above (mic / think poses).  A real hard disconnect is
             * still caught the moment voice goes idle again. */
            time_t now_t = time(NULL);
            voice_state_t vs = voice_state(voice);
            int voice_busy = (vs == VOICE_RECORDING || vs == VOICE_TRANSCRIBING ||
                              vs == VOICE_TYPING);
            if (!voice_busy) {
                win_t *fw = &g_win[g_focus];
                int interactive_stall =
                    ssh && ssh_is_connected(ssh) &&
                    fw->last_tx_at > fw->last_rx_at &&
                    (now_t - fw->last_tx_at) > STALL_TX_NORX_S;
                int want_alert = ssh_dead || interactive_stall;
                if (want_alert != stall_alert) {
                    stall_alert = want_alert;
                    mascot_set_alert(mc, stall_alert);
                }
            }

            /* ── SELECT reconnect (only when the session is dead) ──
             * A hard disconnect (lid-close sleep) leaves ssh_dead=1.
             * Pressing SELECT here reuses the loaded config to open a
             * fresh session, so the user recovers without relaunching.
             * While connected, SELECT falls through to keyboard_handle_input
             * as Esc (see the input_down mask below).
             *
             * select_consumed records that THIS frame's SELECT triggered
             * a reconnect.  It can't be derived from ssh_dead because a
             * successful reconnect clears ssh_dead to 0 in this same
             * frame — without an independent flag, that just-used SELECT
             * would slip through to keyboard_handle_input as a stray Esc
             * into the freshly opened session. */
            int select_consumed = 0;
            if (ssh_dead && !modal_capture && (down & KEY_SELECT)) {
                select_consumed = 1;
                terminal_write(term,
                    "\x1b[33mSelect a machine to reconnect...\x1b[0m\r\n");
                /* Put the crab into its "looking up / waiting" pose, then open
                 * the machine picker.  The idle-loop picker handler performs
                 * the (blocking) reconnect + keychain bootstrap + project-page
                 * raise on confirm — the same path as startup — so a recovered
                 * session lands in exactly the state a fresh connect would.
                 * Flush one frame now so the user sees the picker, not a
                 * frozen screen. */
                mascot_set_reconnecting(mc, 1);
                machine_ui_open(g_mui, &g_cfg, g_cfg.selected_machine,
                                softkb_ui_lang(kb));
                render_frame(r, top, bot, term, kb, kbd, mc, voice,
                             NULL, dual_term, NULL);
                mascot_set_reconnecting(mc, 0);
            }

            /* ── Physical keys (Esc / Enter / BS / D-pad / R / scroll) ──
             * When the AI-ask modal is showing (or animating), suppress
             * the keyboard handler entirely so A=close-keep doesn't
             * also fire Enter to the SSH terminal, B=close-clear
             * doesn't also fire Backspace, etc.  We pass `down=0` so
             * the handler still ticks held-state timers (keeping
             * modifier release detection coherent for the post-modal
             * world) but registers no edge events. */
            u32 input_down = modal_capture ? 0u : down;
            /* Mask SELECT when the session is dead or was just consumed by
             * the reconnect above, so it isn't emitted as Esc. */
            if (ssh_dead || select_consumed) input_down &= ~KEY_SELECT;
            /* The Circle Pad drives the terminal's scrollback, so suppress it
             * whenever a page owns the panel that scrollback would be seen on:
             * the settings page (both panels are its own) and the project card
             * page (project_ui_draw_top replaces the top panel).  The debug
             * overlay is deliberately NOT in this list — it keeps the terminal
             * on the top panel and its own legend advertises
             * "Circle=scrollback". */
            int cpad_scroll = (softkb_settings_open(kb) || pui_up || mui_up) ? 0 : cpad.dy;
            const char *out = keyboard_handle_input(kbd, term, input_down, held,
                                  cpad_scroll);
            /* keyboard_out_len(), not strlen(): Ctrl-Space and Ctrl-@
             * emit a single NUL, and strlen() of a buffer whose only
             * byte is 0x00 is 0 — which would silently drop the key. */
            if (out && !modal_capture)
                send_to_ssh(ssh, g_focus, out, keyboard_out_len(kbd), mc);

            /* ── Touch / soft keyboard ──
             * tx/ty/touch_* were read at the top of the frame; the project
             * page already had its look at them above. */
            int show_mascot = !dual_term && !pui_up &&
                              !softkb_in_debug(kb) &&
                              !softkb_settings_open(kb) &&
                              softkb_mascot_enabled(kb);
            /* The frame the project page closes, the finger that dismissed
             * it may still be down.  softkb derives its down-edge from
             * prev_pressed, so handing it the real coordinates now would
             * fire whichever key sits under the finger — pass (-1,-1) until
             * the gesture ends.  That still updates prev_pressed, which is
             * the whole point. */
            if (!touch_pressed) g_touch_swallow = 0;
            const char *kt = NULL;
            if (modal_capture) {
                /* While the AI-ask modal owns the screen, any bottom-screen
                 * tap dismisses it (= clear history).  Block all routing
                 * to softkb / mascot — and swallow the rest of the
                 * gesture too, or the still-held touch would be
                 * re-hit-tested against the ⚙ badge on the next frame
                 * and pop the settings page open under the stylus.
                 * Stops at the close, not at the end of the fade-out: a
                 * tap during the 12-frame fade-out would otherwise land on
                 * the soft keyboard underneath and type a stray character. */
                if (touch_down) {
                    voice_ai_close_clear(voice);
                    ai_modal_close(aim);
                    g_touch_swallow = 1;
                }
            } else if (pui_up || mui_up) {
                /* The page consumed this frame's touch itself (either
                 * hit-testing its own widgets or lending the coordinates to
                 * the borrowed soft keyboard).  The machine picker has to be
                 * in this list for the same reason the project page is, and
                 * it is not a formality: with the rename field up, the page
                 * block above has ALREADY called softkb_touch with the armed
                 * gate, so falling through to the generic branch below would
                 * press the same key twice and type two characters per tap. */
            } else if (dual_term) {
                /* Dual-screen one-terminal mode: the bottom screen is terminal
                 * space, not a keyboard — taps are ignored. */
            } else if (g_touch_swallow) {
                (void)softkb_touch(kb, kbd, -1, -1, touch_pressed);
            } else if (touch_down && ty >= SOFTKB_BOTTOM_ROW_Y && show_mascot) {
                if (mascot_hit_test(mc, tx, ty))
                    mascot_on_touched(mc, tx);
            } else {
                /* Pass the held flag (not just the down-edge) so softkb
                 * can detect holds for auto-repeat.  softkb derives the
                 * down-edge internally from prev_pressed.  On no-touch
                 * frames this also runs the release-fade path. */
                kt = softkb_touch(kb, kbd, tx, ty, touch_pressed);
                if (kt) send_to_ssh(ssh, g_focus, kt, (int)strlen(kt), mc);
            }

            /* Mascot ticks only when it's actually being shown.  When
             * paused this way it freezes in place; on re-enable it
             * resumes from wherever it stopped. */
            if (show_mascot) {
                mascot_set_species(mc, softkb_mascot_species(kb));
                mascot_update(mc);
            }

            /* ── Render ── */
            render_frame(r, top, bot, term, kb, kbd, mc, voice, aim,
                         dual_term, g_pui);
        }

        /* Release the aux channels BEFORE freeing the session — voice_free →
         * release_aux and project_ui_free → ssh_aux_close would otherwise
         * call libssh2_channel_* on a freed LIBSSH2_SESSION (use-after-free).
         * The project page's own free sits in the cleanup block below, well
         * past this point, so its channel has to be released here instead. */
        /* Last chance for a card edit whose write kept failing (busy or
         * missing card).  ui->dirty is the only record that the in-memory
         * settings still differ from the file, and it dies with g_pui on the
         * next line — there is no next frame to retry in, so this one
         * attempt is synchronous and ignores the cooldown. */
        if (project_ui_dirty(g_pui))
            (void)project_settings_save(g_pui, kb);
        if (g_pui) project_ui_close(g_pui);
        voice_abort(voice);
        if (ssh) ssh_disconnect(ssh);
    }
    if (g_tailscale) {
        ts3ds_close(g_tailscale);
        g_tailscale = NULL;
        tailscale_debug_flush(&g_tailscale_debug, term);
    }
    net_fini();

cleanup:
    if (g_tailscale) {
        ts3ds_close(g_tailscale);
        g_tailscale = NULL;
        tailscale_debug_flush(&g_tailscale_debug, term);
    }
    /* Wipe every machine's credentials plus the shared Tailscale key. */
    for (int i = 0; i < DSSH_MACHINES_MAX; i++) {
        clear_secret(g_cfg.machines[i].passphrase,
                     sizeof(g_cfg.machines[i].passphrase));
        clear_secret(g_cfg.machines[i].macos_keychain_password,
                     sizeof(g_cfg.machines[i].macos_keychain_password));
    }
    clear_secret(g_cfg.tailscale_auth_key,
                 sizeof(g_cfg.tailscale_auth_key));
    if (aim)   ai_modal_free(aim);
    if (g_pui) { project_ui_free(g_pui); g_pui = NULL; }
    if (g_mui) { machine_ui_free(g_mui); g_mui = NULL; }
    if (voice) voice_free(voice);
    if (ime)  ime_free(ime);
    if (mc)   mascot_free(mc);
    if (kb)   softkb_free(kb);
    if (kbd)  keyboard_free(kbd);
    if (r)    renderer_free(r);
    /* `term` aliases g_win[0].term — free through the table so the extra
     * windows' grids go too, and no terminal gets freed twice. */
    for (int i = 0; i < MAX_WINDOWS; i++) {
        if (g_win[i].term) {
            terminal_free(g_win[i].term);
            g_win[i].term = NULL;
        }
    }
    if (romfs_ok) romfsExit();
    audio_exit();
    C2D_Fini();
    C3D_Fini();
    gfxExit();
    return 0;
}

/* ── Project cards ───────────────────────────────────────────────────
 * Everything the card page needs from this side of the fence: turning a
 * card into bytes on a shell channel, and remembering where each window
 * was last told to go.
 *
 * The page itself (source/project_ui.c) owns the list, the editor and the
 * presets; it knows nothing about SSH windows.  That split is what lets
 * one page serve three entry points — after the handshake, on a new
 * window, and from the settings list.
 */

/* Send a card's command to one window's shell channel.
 *
 * A window created by the X+Y+▲ chord is still W_OPENING for a frame or
 * two (ssh_open_shell round-trips), and ssh_write_slot refuses a channel
 * that is not live — so the line is parked and the main loop ships it the
 * frame the slot goes live.  Dropping it instead would make "open a window
 * and pick a card" silently do nothing, which is the one case the feature
 * exists for. */
static void project_queue_or_send(ssh_client_t *ssh, int slot,
                                  const dssh_project_t *proj) {
    if (!ssh || !proj || slot < 0 || slot >= MAX_WINDOWS) return;

    char line[DSSH_PROJECT_PATH_MAX + DSSH_PROJECT_CMD_MAX + 32];
    int n = dssh_project_command(proj, line, (int)sizeof(line) - 2);
    if (n <= 0) return;                    /* nothing to run */
    line[n++] = '\n';
    line[n]   = 0;

    if (ssh_slot_state(ssh, slot) == SSH_SLOT_LIVE) {
        ssh_write_slot(ssh, slot, line, n);
    } else {
        snprintf(g_pending_cmd[slot], sizeof(g_pending_cmd[slot]), "%s", line);
    }

    /* Remember the cd target: it is the honest answer to "which directory
     * is this window in", and the card page asks for it when the user next
     * edits a card.  A raw card owns its own cd, so we learn nothing. */
    if (!proj->raw && proj->path[0])
        snprintf(g_win_cwd[slot], sizeof(g_win_cwd[slot]), "%s", proj->path);
}

/* The user picked card `idx` for window `slot`: run it, count the use, and
 * remember the choice so the list opens on it next time. */
static void project_run(ssh_client_t *ssh, int slot, dssh_settings_t *st,
                        int idx) {
    if (!st || idx < 0 || idx >= st->project_count) return;
    dssh_project_t *p = &st->projects[idx];
    project_queue_or_send(ssh, slot, p);
    p->uses++;
    p->last_used = (long)time(NULL);
    st->selected_project = idx;
    settings_save(st, g_settings_path);
    if (g_pui) project_ui_close(g_pui);
}
